"""Writes src/phys_state.f90, the physics state member by member.

    python3 tools/gen_phys_state.py [--check] [--src DIR]

For each of the four state types (model_state, noahmp_state, gf_state, gwdo_state) one routine per job, with one
statement or one clause per member, in declaration order, the #ifdef blocks of the build switches kept around their
members:
  to_device_X, to_host_X   the card copy of every member updated (never the object: it holds the card's pointers)
  copy_X                   member sections assigned, which never reallocates
  zero_X                   every member set to 0 (after allocate_X: new memory is not zero)
  enter_X                  for a type with allocatable members: the object and its members put on the card
The members come from the type bodies, through the parser of tools/gen_phys_check.py.
--check writes nothing and exits 1 with `DIFFERS src/phys_state.f90`; --src DIR reads the type bodies from DIR.
"""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
import gen_phys_check as parser

root = Path(__file__).resolve().parents[1]
# short name in the routines, file, type, module
TYPES = [('state', 'state', 'state_type', 'model_state'), ('land', 'noahmp_state', 'noahmp_state_type', 'noahmp_state'),
         ('gf', 'gf_state', 'gf_state_type', 'gf_state'), ('gwdo', 'gwdo_state', 'gwdo_state_type', 'gwdo_state')]
ZERO = {'real': '0.', 'integer': '0', 'logical': '.false.'}


def fields(short, src=None):
    _, fname, tname, _ = next(t for t in TYPES if t[0] == short)
    return parser.fields((src or root / 'src') / (fname + '.f90'), tname)


def member_names(short, src=None):
    """the members of the default build (no build switch set, no SFC2_FIELDS), in declaration order"""
    out, depth = [], 0
    for f in fields(short, src):
        if isinstance(f, str):
            depth += 1 if f.startswith('#if') else -1 if f.startswith('#endif') else 0
        elif depth == 0 and not (short == 'land' and f['name'] in parser.SFC2_FIELDS):
            out.append(f['name'])
    return out


def is_allocatable(short, src=None):
    return any(f['allocatable'] for f in fields(short, src) if not isinstance(f, str))


def per_member(items, statement):
    """one statement per member; the switch lines as they are"""
    return [f if isinstance(f, str) else ' ' + statement(f) for f in items]


def clauses(items, directive, width=110):
    """`!$acc <directive>(s%a, s%b, ...)` lines of at most about `width` characters; a switch line ends the current one"""
    out, cur = [], []

    def flush():
        if cur:
            out.append(' !$acc %s(%s)' % (directive, ', '.join(cur)))
            cur.clear()
    for f in items:
        if isinstance(f, str):
            flush()
            out.append(f)
            continue
        if cur and len(', '.join(cur)) + len(f['name']) + 4 > width:
            flush()
        cur.append('s%' + f['name'])
    flush()
    return out


def section(f):
    return '(%s)' % ','.join(':' * f['rank']) if f['rank'] else ''


def generate(src=None):
    o = ['! GENERATED by tools/gen_phys_state.py from the type definitions in src/ - do not edit.',
         '! The physics state member by member, for the card (updates, and the first copy of a type with',
         '! allocatable members), the stash of a check, and the zeros of new memory.',
         '! No whole-object directive or assignment: an object with allocatable members holds addresses, not the fields.',
         'module phys_state']
    o += [' use %s, only: %s' % (mod, tname) for _, _, tname, mod in TYPES]
    o += [' implicit none', ' private']
    for short, _, _, _ in TYPES:
        names = ['zero', 'to_device', 'to_host', 'copy'] + (['enter'] if is_allocatable(short, src) else [])
        o.append(' public :: ' + ', '.join('%s_%s' % (n, short) for n in names))
    o += ['contains']
    for short, _, tname, _ in TYPES:
        items = fields(short, src)
        target = ' type(%s), target, intent(inout) :: s' % tname
        o += ['', ' ! ---- %s ----' % tname]
        o += [' subroutine zero_%s(s)' % short, ' type(%s), intent(inout) :: s' % tname]
        o += per_member(items, lambda f: 's%%%s = %s' % (f['name'], ZERO[f['type'].split('(')[0].strip().lower()]))
        o += [' end subroutine', '']
        if is_allocatable(short, src):
            o += [' subroutine enter_%s(s)' % short, target, ' !$acc enter data copyin(s)']
            o += clauses(items, 'enter data copyin')
            o += [' end subroutine', '']
        o += [' subroutine to_device_%s(s)' % short, target]
        o += clauses(items, 'update device')
        o += [' end subroutine', '', ' subroutine to_host_%s(s)' % short, target]
        o += clauses(items, 'update self')
        o += [' end subroutine', '',
              ' subroutine copy_%s(from, to)' % short, ' type(%s), intent(in) :: from' % tname,
              ' type(%s), intent(inout) :: to' % tname]
        o += per_member(items, lambda f: 'to%%%s%s = from%%%s' % (f['name'], section(f), f['name']))
        o += [' end subroutine']
    o += ['end module']
    return '\n'.join(o) + '\n'


def main():
    src = Path(sys.argv[sys.argv.index('--src') + 1]) if '--src' in sys.argv else None
    text = generate(src)
    path = root / 'src' / 'phys_state.f90'
    if '--check' in sys.argv:
        if not path.exists() or path.read_text() != text:
            print('DIFFERS src/phys_state.f90')
            return 1
        return 0
    path.write_text(text)
    print('wrote src/phys_state.f90')
    return 0


if __name__ == '__main__':
    sys.exit(main())
