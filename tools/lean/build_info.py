"""The Fortran build identity (name, flavor, switches, git, profile), generated at configure time into the build
directory, with the platform facts the program needs from C (the errno accessor and EWOULDBLOCK, for the
run-directory lock of src/run/lean_guard.f90) and the card's largest kernel stack frame for the card memory check."""
import platform
import re
import subprocess
from pathlib import Path
from typing import Optional

from tools.lean.config import ROOT, BuildConfig, build_dir_name, build_flavor, switch_defines

# per OS: the C function that returns errno's address, and EWOULDBLOCK (flock on a locked directory)
ERRNO = {'Linux': ('__errno_location', 11), 'Darwin': ('__error', 35)}
GENERATED = 'generated/lean_build_info.f90'


def git_describe(root: Path = ROOT) -> str:
    # MPAS Makefile:1020-1026 records unknown when git cannot describe the source.
    try:
        done = subprocess.run(['git', '-C', str(root), 'describe', '--dirty', '--always'],
                              capture_output=True, text=True)
    except OSError:
        return 'unknown'
    return done.stdout.strip() if done.returncode == 0 else 'unknown'


def _character(name: str, value: str) -> str:
    prefix = f' character(len=*), parameter :: {name} = '
    pieces, piece = [], ''
    for char in value:
        escaped = "''" if char == "'" else char
        if len(piece) + len(escaped) > 100:
            pieces.append(piece)
            piece = ''
        piece += escaped
    pieces.append(piece)
    if len(pieces) == 1 and len(prefix) + len(piece) + 2 <= 132:
        return prefix + "'" + piece + "'"
    return prefix + '&\n' + '// &\n'.join("  '" + part + "'" for part in pieces)


def recorded_frame(path: Path) -> int:
    """The card_frame_bytes an existing lean_build_info.f90 holds (0 when there is none)."""
    try:
        found = re.search(r'card_frame_bytes = (\d+)', path.read_text(encoding='utf-8'))
    except OSError:
        return 0
    return int(found.group(1)) if found else 0


def build_info_text(cfg: BuildConfig, describe: Optional[str] = None, system: Optional[str] = None,
                    frame: int = 0) -> str:
    """The text of lean_build_info.f90. frame: the card's largest kernel stack frame in bytes, which the card memory
    check needs (a gpu build writes it after its first link: build.link_frame; a cpu build always 0)."""
    system = platform.system() if system is None else system
    if system not in ERRNO:
        raise ValueError(f'unsupported build system {system!r}')
    accessor, would_block = ERRNO[system]
    switches = set(switch_defines(cfg))
    values = {
        'build_name': build_dir_name(cfg),
        'build_flavor': build_flavor(cfg),
        'build_switches': ' '.join(sorted(switches)),
        'build_git': git_describe() if describe is None else describe,
        'build_profile': cfg.profile + ('-' + cfg.variant if cfg.variant else ''),
    }
    lines = [f'! Generated by tools/lean/build_info.py for {build_dir_name(cfg)}.',
             'module lean_build_info',
             ' use iso_c_binding, only: c_ptr, c_int',
             ' implicit none',
             ' private',
             ' public :: build_name, build_flavor, build_switches, build_git, build_profile, build_openmp, build_openacc',
             ' public :: errno_would_block, errno_location, card_frame_bytes']
    lines += [_character(name, value) for name, value in values.items()]
    lines += [f' logical, parameter :: build_openmp = {".true." if cfg.omp else ".false."}',
              f' logical, parameter :: build_openacc = {".true." if cfg.target == "gpu" else ".false."}',
              f' integer(c_int), parameter :: errno_would_block = {would_block}',
              f' integer, parameter :: card_frame_bytes = {frame if cfg.target == "gpu" else 0}',
              ' interface',
              f"  function errno_location() bind(C, name='{accessor}') result(p)",
              '   import :: c_ptr',
              '   type(c_ptr) :: p',
              '  end function',
              ' end interface',
              'end module', '']
    return '\n'.join(lines)


def write_build_info(cfg: BuildConfig, build_dir: Path, describe: Optional[str] = None,
                     system: Optional[str] = None, frame: Optional[int] = None) -> Path:
    """frame None keeps the frame the file holds (a configure does not undo the frame of the last link)."""
    path = build_dir / GENERATED
    text = build_info_text(cfg, describe, system, recorded_frame(path) if frame is None else frame)
    if not path.is_file() or path.read_text(encoding='utf-8') != text:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding='utf-8')
    return path
