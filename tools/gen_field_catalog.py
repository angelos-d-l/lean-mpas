#!/usr/bin/env python3
"""Writes src/run/lean_field_catalog.f90: every variable MPAS 8.4.2 can write (name, dimensions, default, attributes,
packages), in the field order of src/run/lean_stream_registry.f90, and the Registry's dimensions. Read from MPAS
8.4.2's Registry.xml (reference/mpas_src, ./lean fetch-upstream).

    python3 tools/gen_field_catalog.py [--check]

--check writes nothing and prints DIFFERS src/run/lean_field_catalog.f90 (exit 1); exit 2 without the Registry."""
import argparse
from dataclasses import dataclass
import hashlib
from pathlib import Path
import sys
import xml.etree.ElementTree as ET
if __package__ in (None, ''):
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from tools.gen_namelist import ROOT, REGISTRY, preprocess, fortran_string
from tools.gen_stream_registry import load as stream_load, merge, packages
OUT = Path('src/run/lean_field_catalog.f90')
IGNORED = {'name','type','dimensions','persistence','packages','time_levs','name_in_code','array_group','default_value'}
@dataclass
class Variable:
    name: str
    field: int
    constituent: int
    packages: int
    type: int
    dims: str
    time: bool
    default: str
    first: int
    count: int
@dataclass
class Catalog:
    variables: list
    attributes: list
    dimensions: list
    sha256: str
    nfields: int

def load(registry=REGISTRY):
    text=preprocess(Path(registry))
    root=ET.fromstring(text)
    streams=stream_load(registry)
    fields={f.name:i+1 for i,f in enumerate(streams.fields)}
    pkgs=[p[0] for p in streams.packages]
    variables, attributes=[],[]
    for struct in root.findall('var_struct'):
        for el in struct:
            if 'packages' not in el.attrib and 'packages' in struct.attrib:
                el.set('packages',struct.attrib['packages'])
            if el.tag=='var_array':
                for var in el:
                    if 'packages' not in var.attrib and 'packages' in el.attrib:
                        var.set('packages',el.attrib['packages'])
    for struct in merge(root.findall('var_struct')):
        for el in merge(struct.findall('var_array'))+struct.findall('var'):
            members=el.findall('var') if el.tag=='var_array' else [el]
            for j,var in enumerate(members):
                first=len(attributes)+1
                # MPAS src/tools/registry/gen_inc.c:34-58,1583-1594,1783-1794: preserve XML attribute order.
                for name,value in var.attrib.items():
                    if name in IGNORED or (el.tag=='var_array' and name=='missing_value'):
                        continue
                    name={'description':'long_name','missing_value':'_FillValue'}.get(name,name)
                    # MPAS's Registry_noahmp.xml gives them s m^{-1}: these exchange coefficients are speeds.
                    if name=='units' and var.attrib['name'] in ('chvxy','chbxy'):
                        value='m s^{-1}'
                    attributes.append((name,value,name=='_FillValue'))
                if el.tag=='var_array' and 'missing_value' in el.attrib:
                    attributes.append(('_FillValue',el.attrib['missing_value'],True))
                dims=el.get('dimensions','').split()
                kind={'real':1,'integer':2,'text':3}[el.attrib['type']]
                default=el.get('default_value',el.get('missing_value', '0.0' if kind==1 else '0'))
                variables.append(Variable(var.attrib['name'],fields[el.attrib['name']],j+1 if el.tag=='var_array' else 0,
                    sum(1<<pkgs.index(p) for p in set(packages(var))), kind,
                    ' '.join(d for d in dims if d!='Time'),'Time' in dims,default,first,len(attributes)-first+1))
    # Match load() even if a Registry interleaves arrays and plain fields.
    variables.sort(key=lambda v:(v.field,v.constituent))
    return Catalog(variables,attributes,[(d.attrib['name'],d.get('definition','')) for d in root.findall('dims/dim')],
                   hashlib.sha256(text.encode()).hexdigest(),len(streams.fields))

def fortran_module(t):
    lines=['! Generated by tools/gen_field_catalog.py from MPAS 8.4.2 Registry.xml; do not edit.',
           '! The variables MPAS writes, in stream-registry field order, with their attributes in the order of',
           '! MPAS src/tools/registry/gen_inc.c:34-58,1583-1594,1783-1794.',
           'module lean_field_catalog',' use lean_stream_registry, only: N_FIELDS',' implicit none',
           ' integer, parameter :: CAT_REAL=1, CAT_INTEGER=2, CAT_TEXT=3',
           f' integer, parameter :: N_VARS={len(t.variables)}, N_ATTS={len(t.attributes)}, N_DIMS={len(t.dimensions)}',
           f" character(len=64), parameter :: REGISTRY_SHA256 = '{t.sha256}'"]
    def array(name,values,kind):
        for part,first in enumerate(range(0,len(values),100),1):
            chunk=values[first:first+100]
            lines.append(f' {kind}, parameter :: {name}_{part}({len(chunk)}) = [ &')
            if kind.startswith('character'): lines.append(f'  {kind} :: &')
            for i,v in enumerate(chunk):
                # Split long literals without changing embedded spaces.
                if len(v)>110 and v.startswith("'"):
                    raw=v[1:-1].replace("''", "'")
                    pieces=[fortran_string(raw[k:k+85]) for k in range(0,len(raw),85)]
                    lines.extend('  '+p+'// &' for p in pieces[:-1])
                    v=pieces[-1]
                lines.append('  '+v+(', &' if i<len(chunk)-1 else ' ]'))
        lines.append(f' {kind}, parameter :: {name}({len(values)}) = [ &')
        parts=[f'{name}_{p}' for p in range(1,(len(values)+99)//100+1)]
        lines.extend('  '+p+(', &' if i<len(parts)-1 else ' ]') for i,p in enumerate(parts))
    def strings(n,vs,length):
        if any(len(v)>length for v in vs): raise ValueError(n+' exceeds fixed length')
        array(n,[fortran_string(v) for v in vs],f'character(len={length})')
    for name,prop,length in [('VAR_NAME','name',32),('VAR_DIMS','dims',48),('VAR_DEFAULT','default',24)]:
        strings(name,[getattr(v,prop) for v in t.variables],length)
    for name,prop in [('VAR_FIELD','field'),('VAR_CONSTITUENT','constituent'),('VAR_PACKAGES','packages'),('VAR_TYPE','type'),('VAR_ATT_FIRST','first'),('VAR_ATT_COUNT','count')]:
        array(name,[str(getattr(v,prop)) for v in t.variables],'integer')
    array('VAR_TIME',['.true.' if v.time else '.false.' for v in t.variables],'logical')
    strings('ATT_NAME',[a[0] for a in t.attributes],16)
    strings('ATT_TEXT',[a[1] for a in t.attributes],168)
    array('ATT_NUMERIC',['.true.' if a[2] else '.false.' for a in t.attributes],'logical')
    array('FIELD_FIRST_VAR',[str(next(i+1 for i,v in enumerate(t.variables) if v.field==f)) for f in range(1,t.nfields+1)],'integer')
    array('FIELD_VAR_COUNT',[str(sum(v.field==f for v in t.variables)) for f in range(1,t.nfields+1)],'integer')
    strings('DIM_NAME',[d[0] for d in t.dimensions],16)
    strings('DIM_DEFINITION',[d[1] for d in t.dimensions],40)
    lines.append('contains')
    for name,count in [('var','VARS'),('dim','DIMS')]:
        lines.extend([f' integer function {name}_index(name) result(idx)','  character(len=*), intent(in) :: name','  integer :: i','  idx=0',f'  do i=1,N_{count}',f'   if ({name.upper()}_NAME(i) /= name) cycle','   idx=i','   return','  end do',' end function'])
    return '\n'.join(lines+['end module',''])

def main(argv=None):
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--root',type=Path,default=ROOT)
    p.add_argument('--registry',type=Path,default=REGISTRY)
    p.add_argument('--check',action='store_true')
    a=p.parse_args(argv)
    if not a.registry.is_file():
        print(f'E_NO_REGISTRY {a.registry} (./lean fetch-upstream)',file=sys.stderr); return 2
    data=fortran_module(load(a.registry))
    path=a.root/OUT
    if a.check:
        if not path.is_file() or path.read_text()!=data:
            print('DIFFERS '+str(OUT)); return 1
    else:
        path.parent.mkdir(parents=True,exist_ok=True); path.write_text(data)
    return 0
if __name__=='__main__': sys.exit(main())
