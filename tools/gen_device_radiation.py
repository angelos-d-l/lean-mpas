def stops_to_fault(lines, name):
    """`[error] stop 'message'` -> call physics_fault(code), `use lean_phys_fault` in the modules that now call it"""
    pat = re.compile(r"""\b(?:error\s+)?stop\s*(['"])(.*?)\1""", re.I)
    out, n = [], 0
    for s in lines:
        m = pat.search(dg.code_of(s))
        if m:
            s = s[:m.start()] + 'call physics_fault(%d)' % STOP_CODES[m.group(2)] + s[m.end():]
            n += 1
        out.append(s)
    if n != STOP_COUNT.get(name, 0):
        raise SystemExit('%s: %d stops converted, expected %d' % (name, n, STOP_COUNT.get(name, 0)))
    idx = [i for i, s in enumerate(out) if dg.MODULE.match(s)]
    ends = [i for i, s in enumerate(out) if dg.END_MODULE.match(s)]
    mark = {a for a, b in zip(idx, ends) if any('call physics_fault(' in out[k] for k in range(a, b))}
    res = []
    for i, s in enumerate(out):
        res.append(s)
        if i in mark:
            res.append(' use lean_phys_fault, only: physics_fault')
    return res


# the host-only remarks of the sources that are false in the device versions: (file, old text, new text or None to drop the line)
HOST_REMARKS = [
    ('radiation_column', '! One RRTMG call for one column on the host: ', '! One RRTMG call for one column: '),
    ('radiation_column', ' ! Both are recursive so that the locals are on the stack of each OpenMP thread, not shared static storage.', None),
    ('radiation_prepare', ' value, and the layer means. recursive: called from the OpenMP radiation loop, its locals on each thread\'s stack.',
     ' value, and the layer means.'),
]


def host_remarks(lines, name):
    out = list(lines)
    for file, old, new in HOST_REMARKS:
        if file != name:
            continue
        k = [i for i, s in enumerate(out) if old in s]
        if len(k) != 1:
            raise SystemExit('%s: %d lines hold the host remark %r' % (name, len(k), old))
        if new is None:
            del out[k[0]]
        else:
            out[k[0]] = out[k[0]].replace(old, new)
    return out


def common(lines, name):
    """card copies of the tables, no version strings, no `recursive` (the card has no use for it) and no remark about it,
    fatal stops as fault codes"""
    out = []
    for s in host_remarks(lines, name):
        if re.match(r'^\s*use\s+rr(lw|sw)_vsn\b', s, re.I):
            continue
        s = re.sub(r'^(\s*use\s+)(rr(?:lw|sw)_(?:cld|con|kg\d+|ref|tbl|wvn|aer))\b', r'\1lean_dev_\2', s, flags=re.I)
        s = re.sub(r'^(\s*use\s+)module_ra_rrtmg_lw\s*,\s*only\s*:\s*retab\s*$', r'\1lean_dev_retab, only: retab', s, flags=re.I)
        s = re.sub(r'^(\s*)recursive\s+(subroutine|function)\b', r'\1\2', s, flags=re.I)
        out.append(s)
    return stops_to_fault(fatal_to_fault(out, name), name)


def promote_internal(lines, parent):
    """the internal procedures of `parent` (taugb1..16, taumol16..29: own locals and own `use` of same-named tables, so they cannot be
    inlined) become module procedures with the argument list and the argument declarations of the parent (which has no locals);
    intent(out) of the copies is intent(inout), each band writes only its own g-points"""
    i, contains, end = dg.routine_span(lines, parent)
    h = dg.header_end(lines, i)
    head = ' '.join(dg.code_of(x).rstrip().rstrip('&') for x in lines[i:h + 1])
    args = head[head.index('(') + 1:head.rindex(')')]
    k = h + 1
    while not dg.CALL.match(lines[k]):
        k += 1
    decls = [re.sub(r'intent\s*\(\s*out\s*\)', 'intent(inout)', s, flags=re.I) for s in lines[h + 1:k] if re.search(r'\bintent\b', s, re.I)]
    assert not any(dg.DECL_START.match(dg.code_of(s)) and not re.search(r'\bintent\b', s, re.I) for s in lines[h + 1:k]), 'parent %s has locals' % parent
    procs, order = dg.parse_internal(lines, contains, end)
    body = []
    for s in lines[h + 1:contains]:
        m = dg.CALL.match(s)
        if m and m.group(2).lower() in procs:
            s = '%scall %s(%s)' % (m.group(1), m.group(2), args)
        body.append(s)
    new = []
    for name in order:
        b = procs[name]
        u = 0
        while u < len(b) and re.match(r'^\s*(use|implicit)\b', b[u], re.I):
            u += 1
        new += ['subroutine %s(%s)' % (name, args)] + b[:u] + decls + b[u:] + ['end subroutine %s' % name]
    return lines[:h + 1] + body + [lines[end]] + new + lines[end + 1:]


def climatology(lines):
    """the ozone tables on the card too (ozone_at_lat_time computes a column's ozone there)"""
    out = []
    for x in lines:
        out.append(x)
        if re.match(r'^\s*real\s*::\s*table_pressure\(59\),latitude\(64\),ozone_table\(59,64,12\)\s*$', x):
            out.append(' !$acc declare create(latitude,ozone_table)')
    i = next(k for k, x in enumerate(out) if re.match(r'^\s*pin=table_pressure\s*$', x))
    out.insert(i + 1, ' !$acc update device(latitude,ozone_table)')
    assert sum('declare create(latitude' in x for x in out) == 1
    return out


def after_uses(lines):
    """`!$acc routine seq` after the `use` statements of the procedure (it is a specification directive)"""
    out = list(lines)
    i = 0
    while i < len(out):
        if out[i].strip().lower() == '!$acc routine seq':
            j = i + 1
            while j < len(out) and re.match(r'^\s*use\b', out[j], re.I):
                j += 1
            if j > i + 1:
                out[i:j] = out[i + 1:j] + [out[i]]
                i = j - 1
        i += 1
    return out


def seq_all(lines, skip=()):
    skip = {s.lower() for s in skip}
    return after_uses(dg.add_routine_seq(lines, [n for n, _ in dg.module_procedures(lines) if n.lower() not in skip]))


def contiguous_play(lines, decl, extent):
    """the pressure column of the ozone interpolation as a contiguous copy: the section play(1,:) as an actual
    argument is a temporary the card compiler allocates with device malloc, which is serialised over the whole card"""
    k = [i for i, s in enumerate(lines) if re.match(r'^\s*call\s+ozone_to_layers\(\s*\w+\s*,\s*play\(1,:\)', s, re.I)]
    d = [i for i, s in enumerate(lines) if re.match(decl, s, re.I)]
    assert len(k) == 1 and len(d) == 1, (k, d)
    out = list(lines)
    out[k[0]] = out[k[0]].replace('play(1,:)', 'play1')
    out[k[0]:k[0]] = ['play1(kts:nlay) = play(1,kts:nlay)   ! contiguous active pressure column; no temporary at the call']
    out[d[0] + 1:d[0] + 1] = ['real :: play1(%s)' % extent]
    return out


RECIPES = {
    'radiation_lw_kernels': lambda L: seq_all(promote_internal(L, 'taumol')),
    'radiation_sw_kernels': lambda L: seq_all(promote_internal(L, 'taumol_sw')),
    'radiation_lw': lambda L: seq_all(contiguous_play(dg.inline_internal(L, 'radiation_lw_column'), r'^\s*real\s*::\s*play\(1,kts:max_lw_layers\)\s*$', 'kts:max_lw_layers')),
    'radiation_sw': lambda L: seq_all(contiguous_play(dg.inline_internal(L, 'radiation_sw_column'), r'^\s*real\s*,\s*dimension\(1,kts:max_sw_layers\)\s*::\s*play,', 'kts:max_sw_layers')),
    'radiation_cloud': seq_all,
    'radiation_ozone': seq_all,
    'radiation_prepare': seq_all,
    'radiation_climatology': lambda L: climatology(after_uses(dg.add_routine_seq(L, ['ozone_at_time', 'ozone_at_lat_time']))),
    'radiation_column': lambda L: after_uses(dg.add_routine_seq(L, ['radiation_event_ws'])),
}


def generate():
    t, _ = tables()
    result = {'radiation_device_tables': t}
    for name, recipe in RECIPES.items():
        lines = (root / 'src' / (name + '.f90')).read_text().split('\n')
        lines = capacity_locals(recipe(common(lines, name)))
        result[name] = HEADER % ('src/' + name + '.f90') + '\n'.join(lines)
    return result


if __name__ == '__main__':
    gen = generate()
    out_dir.mkdir(exist_ok=True)
    bad = 0
    for name, text in gen.items():
        p = out_dir / (name + '.f90')
        if '--check' in sys.argv:
            if not p.exists() or p.read_text() != text:
                print('DIFFERS', p); bad += 1
        else:
            p.write_text(text)
            print('wrote', p, len(text.split('\n')), 'lines')
    sys.exit(1 if bad else 0)
