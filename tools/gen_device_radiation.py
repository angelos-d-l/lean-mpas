"""The RRTMG tables and the radiation column code for the card (written into src/device/ like tools/gen_device_physics.py).

The tables live in the data modules of the WRF RRTMG files (rrlw_kg01 ... rrsw_wvn), filled on the host at startup (radiation_tables.f90).
Those modules use EQUIVALENCE (ka/absa), which OpenACC cannot put on the card, so the card gets copies: module lean_dev_<name> with the
same declarations (no EQUIVALENCE, no DATA), `!$acc declare create`, and fill_<name>, which copies the host values and updates the card.
After the copy the two hold the same bits; the card code uses the copies (`use rrlw_kg01` -> `use lean_dev_rrlw_kg01`).

  python3 tools/gen_device_radiation.py           regenerate
  python3 tools/gen_device_radiation.py --check   write nothing; print DIFFERS <path> for each file that differs, exit 1
"""
