def fatal_to_fault(lines, name):
    out, msg, n = [], None, 0
    for s in lines:
        if re.match(r'^\s*write\s*\(\s*errmess\b', s, re.I):
            msg = max(re.findall(r"""['"]([^'"]*)['"]""", s), key=len).strip()   # the message, not the format
            continue
        if re.match(r'^\s*call\s+physics_error_fatal\b', s, re.I):
            out.append('call physics_fault(%d)' % FATAL_CODES[(name, msg)])
            n += 1
            continue
        if re.match(r'^\s*use\s+mpas_atmphys_utilities\b', s, re.I):
            s = 'use lean_phys_fault, only: physics_fault'
        out.append(s)
    expect = FATAL_COUNT.get(name, 0)
    if n != expect:
        raise SystemExit('%s: %d fatal calls converted, expected %d' % (name, n, expect))
    return out


