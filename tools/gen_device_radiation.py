DATA = {'module_ra_rrtmg_lw.F': ['rrlw_cld', 'rrlw_con'] + ['rrlw_kg%02d' % i for i in range(1, 17)] + ['rrlw_ref', 'rrlw_tbl', 'rrlw_wvn'],
        'module_ra_rrtmg_sw.F': ['rrsw_aer', 'rrsw_cld', 'rrsw_con'] + ['rrsw_kg%d' % i for i in range(16, 30)] + ['rrsw_ref', 'rrsw_tbl', 'rrsw_wvn']}


def module_text(lines, name):
    a = next(i for i, s in enumerate(lines) if re.match(r'^\s*module\s+%s\s*$' % name, s, re.I))
    b = next(i for i in range(a, len(lines)) if re.match(r'^\s*end\s+module\s+%s\b' % name, lines[i], re.I))
    return lines[a:b + 1]


def device_module(name, body):
    """lean_dev_<name>: the declarations of module <name> without EQUIVALENCE/DATA, on the card; fill_<name> copies the host values"""
    body = [s for s in body if not re.match(r'^\s*!', s) and s.strip()]
    body = dg.drop_lines(body, [r'^\s*equivalence\b', r'^\s*data\b'])
    names = dg.module_variables(body)
    spec = body[1:-1]
    out = ['module lean_dev_' + name] + spec
    out += dg.acc_list('declare create', names)
    out += ['contains', ' subroutine fill_' + name + '()']
    for k in range(0, len(names), 6):
        out.append('  use %s, only: %s' % (name, ', '.join('h_%s => %s' % (n, n) for n in names[k:k + 6])))
    for n in names:
        out.append('  %s = h_%s' % (n, n))
    out += ['  ' + s.strip() for s in dg.acc_list('update device', names)]
    out += [' end subroutine', 'end module lean_dev_' + name]
    return out, names


def tables():
    text, calls = [], []
    for f, mods in DATA.items():
        lines = (wrf / f).read_text().split('\n')
        for m in mods:
            dev, names = device_module(m, module_text(lines, m))
            text += dev + ['']
            calls.append(m)
    # retab of module_ra_rrtmg_lw (effective radius of ice, used by the SW column)
    text += ['module lean_dev_retab', ' real :: retab(95)', ' !$acc declare create(retab)', 'contains', ' subroutine fill_retab()',
             '  use module_ra_rrtmg_lw, only: h_retab => retab', '  retab = h_retab', '  !$acc update device(retab)', ' end subroutine',
             'end module lean_dev_retab', '']
    calls.append('retab')
    text += ['module lean_dev_rrtmg_tables', ' implicit none', 'contains', ' ! after initialize_radiation_tables: the card copies get the host values',
             ' subroutine rrtmg_tables_to_device()']
    text += ['  use lean_dev_%s, only: fill_%s' % (m, m) for m in calls]
    text += ['  call fill_%s()' % m for m in calls]
    text += [' end subroutine', 'end module lean_dev_rrtmg_tables']
    return (HEADER % 'the data modules of third_party/mpas-8.4.2 module_ra_rrtmg_lw.F and module_ra_rrtmg_sw.F' + AER_NOTICE
            + '\n'.join(text) + '\n', calls)


