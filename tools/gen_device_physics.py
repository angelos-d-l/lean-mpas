POOL_SIZES = {}
POOL_SIZES_BASE = {}   # the same without the Thompson stages (the pools of a LEAN_MICRO_ONEKERNEL build run without LEAN_MICRO_STAGED=1)
POOL_USERS = {}       # pool family -> the routines that use it


def fix_intent(lines):
    """INTENT(IN) on a derived type with pointer components lets the card compiler assume the targets are read-only (loads from the read-only
    cache, stores not seen by later loads: a loop that writes rho_moist through such an argument and reads it back gets zero). The lean
    code writes through such arguments, so they are INTENT(INOUT) in the device versions."""
    pat = re.compile(r'(type\s*\(\s*(?:column_view|gf_column|gwdo_column_state|noahmp_column)\s*\)\s*,\s*)intent\s*\(\s*in\s*\)', re.I)
    return [pat.sub(lambda m: m.group(1) + 'intent(inout)', s) for s in lines]


def device_lines(src, name, build):
    lines = fix_intent(RECIPES[name](faults(src, build)))
    if name == 'gf':
        # The explicit-shape GF dummy uses the active stride. Keep its packed
        # columns in one capacity buffer, without a noncontiguous temporary.
        lines = [re.sub(r'dimension\(1:kte,1:9\)\s*::\s*omeg',
                        'dimension(9*max_levels) :: omeg', line, flags=re.I) for line in lines]
        lines = [re.sub(r'\bomeg\(k,n\)', 'omeg(k+(n-1)*kte)', line, flags=re.I) for line in lines]
    lines = capacity_locals(lines)
    if name == 'gf_core':
        # Each ensemble buffer has one column. Pass its contiguous active
        # vector to the exact-shape dummy, without packing a matrix section.
        for field in ('dellat_ens', 'dellaqc_ens', 'dellaq_ens', 'pwo_ens', 'subt_ens', 'subq_ens'):
            lines = [line.replace(field+'(1:kte,1:1)', field+'(1:kte,1)') for line in lines]
    for routine, layout, *kinds in POOLED.get(name, []):
        lines, used = pool_locals(lines, routine, layout=layout, kinds=kinds[0] if kinds else None)
        for pool, n in used.items():
            POOL_SIZES[pool] = max(POOL_SIZES.get(pool, 0), n)
            if routine not in THOMPSON_STAGES:
                POOL_SIZES_BASE[pool] = max(POOL_SIZES_BASE.get(pool, 0), n)
    if name == 'thompson':
        lines = finish_split(lines)
        lines = thompson_card(lines)
    return lines


# ---- the hand-written card stages of Thompson: tools/thompson_card.f90 is Fortran written by hand (not generated
# from the original); it goes into the device module lean_thompson verbatim, its declarations before the module's CONTAINS and its
# routines before END MODULE, so it reads Thompson's constants and tables. Its marker lines: '!! PUBLIC: a, b' (added to the
# module's public names), '!! DECLARATIONS', '!! ROUTINES'.
THOMPSON_CARD_FILE = root / 'tools' / 'thompson_card.f90'


# The dry points of the generated stages take the constants of thompson_card_start (the same expressions on the same values):
# b2's rain moments where rr = R1 and nr = R2, b1's droplet-number bin idx_n where nc = 2 (its DLOG is double precision)
THOMPSON_DRY = {'mp_thompson_b2': ([
    '         lamr = (am_r*crg(3)*org2*pool_pr(slot_,k,22)/pool_pr(slot_,k,18))**obmr',
    '         pool_pd(slot_,k,6) = 1./lamr',
    '         pool_pr(slot_,k,41) = (3.0 + mu_r + 0.672) / lamr',
    '         pool_pd(slot_,k,8) = pool_pr(slot_,k,22)*org2*lamr**cre(2)'], [
    '         if (pool_pr(slot_,k,18) .eq. R1 .and. pool_pr(slot_,k,22) .eq. R2) then   ! the dry constants (thompson_card_start)',
    '         pool_pd(slot_,k,6) = th_dry_ilamr',
    '         pool_pr(slot_,k,41) = th_dry_mvdr',
    '         pool_pd(slot_,k,8) = th_dry_n0r',
    '         else']),
    'mp_thompson_b1': ([
    '         idx_n = NINT(1.0 + FLOAT(nbc) * DLOG(pool_pr(slot_,k,23)/t_Nc(1)) / nic1)'], [
    '         if (pool_pr(slot_,k,23) .eq. 2.) then   ! the dry constant (thompson_card_start)',
    '         idx_n = th_dry_idxn',
    '         else'])}


# a1's zeroing of the column's rainprod and evapprod: b1 and b2 write them at every level of a column that does not skip, so the
# card zeroes them only for the columns that skip in the last sub-step (src/dyn_micro.f90 micro_staged, its end kernel)
THOMPSON_DROP = {'mp_thompson_a1': ['         rainprod(k) = 0.', '         evapprod(k) = 0.']}


def thompson_dry(lines):
    for routine, old in THOMPSON_DROP.items():
        a = next(i for i, x in enumerate(lines) if re.match(r'\s*subroutine\s+%s\b' % routine, x, re.I))
        b = next(i for i in range(a, len(lines)) if re.match(r'\s*end\s+subroutine\b', lines[i], re.I))
        k = [i for i in range(a, b) if lines[i:i + len(old)] == old]
        if len(k) != 1:
            raise SystemExit('thompson_dry: the statements of %s are not where expected' % routine)
        lines = lines[:k[0]] + ['! (rainprod, evapprod: zeroed by the card for the columns that skip; THOMPSON_DROP in tools/gen_device_physics.py)'] + lines[k[0] + len(old):]
    for routine, (old, head) in THOMPSON_DRY.items():
        a = next(i for i, x in enumerate(lines) if re.match(r'\s*subroutine\s+%s\b' % routine, x, re.I))
        b = next(i for i in range(a, len(lines)) if re.match(r'\s*end\s+subroutine\b', lines[i], re.I))
        k = [i for i in range(a, b) if lines[i:i + len(old)] == old]
        if len(k) != 1:
            raise SystemExit('thompson_dry: the statements of %s are not where expected' % routine)
        k = k[0]
        lines = lines[:k] + head + old + ['         endif'] + lines[k + len(old):]
    return lines


def thompson_card(lines):
    lines = thompson_dry(lines)
    text = THOMPSON_CARD_FILE.read_text().rstrip('\n').split('\n')
    pub = [x.split(':', 1)[1].strip() for x in text if x.startswith('!! PUBLIC:')]
    d = text.index('!! DECLARATIONS')
    r = text.index('!! ROUTINES')
    decls, routines = text[d + 1:r], text[r + 1:]
    p = [i for i, x in enumerate(lines) if re.match(r'^\s*public\s*::.*\bmp_thompson\b', x, re.I)]
    if len(p) != 1:
        raise SystemExit('thompson_card: the public statement is not where expected')
    lines[p[0]] = lines[p[0]].rstrip() + ', ' + ', '.join(pub)
    k = max(m for m, x in enumerate(lines) if dg.END_MODULE.match(x))
    lines = lines[:k] + ['! ---- hand-written: tools/thompson_card.f90 (not generated from the original) ----'] + routines + lines[k:]
    c = next(i for i, x in enumerate(lines) if re.match(r'^\s*contains\s*$', x, re.I))
    return lines[:c] + ['! ---- hand-written: tools/thompson_card.f90 ----'] + decls + lines[c:]


def generate(names=None):
    result = {}
    for name, recipe in RECIPES.items():
        if names and name not in names:
            continue
        src = (root / 'src' / (name + '.f90')).read_text().split('\n')
        lines = device_lines(src, name, name)
        result[name] = HEADER % HEADER_FROM.get(name, 'src/' + name + '.f90') + '\n'.join(lines)
    return result


