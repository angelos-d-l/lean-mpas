# Arrays of mp_thompson whose lives do not overlap share storage on the card (a smaller stack frame, same values): the left ones
# are first written in fall_speeds (vtrk etc. zeroed there for kts:kte+1, sed_* written for every level before they are read)
# and used only there and in the sedimentation; the right ones are dead after evaporate_rain, which runs before fall_speeds.
THOMPSON_SHARED = {'sed_r': 'diffu', 'sed_s': 'visco', 'sed_g': 'vsc2', 'sed_i': 'qvs', 'sed_n': 'ssatw', 'vtik': 'ssati',
                   'vtrk': 'rhof2', 'vtnrk': 'mvd_c', 'vtsk': 'nwfa'}


def share_thompson_storage(lines):
    start = next(i for i, x in enumerate(lines) if re.match(r'\s*subroutine\s+mp_thompson\b', x, re.I))
    end = next(i for i in range(start, len(lines)) if re.match(r'\s*end\s+subroutine\s+mp_thompson\b', lines[i], re.I))
    out = lines[:start]
    body = lines[start:end + 1]
    # the local REAL level-array declarations (one statement may continue on the next line)
    i = 0
    new = []
    while i < len(body):
        x = body[i]
        if re.match(r'\s*REAL\s*,\s*DIMENSION\(kts:kte(\+1)?\)\s*::', x, re.I) and 'INTENT' not in x.upper():
            stmt = [x]
            while stmt[-1].rstrip().endswith('&'):
                i += 1
                stmt.append(body[i])
            text = ' '.join(t.rstrip().rstrip('&') for t in stmt)
            head, rest = text.split('::', 1)
            keep = [n.strip() for n in rest.split(',') if n.strip()]
            keep = [n for n in keep if n.lower() not in THOMPSON_SHARED and n.lower() not in THOMPSON_SHARED.values()]
            if keep:
                new.append(head.rstrip() + ':: ' + ', '.join(keep))
            i += 1
            continue
        new.append(x)
        i += 1
    decl = next(k for k, x in enumerate(new) if re.match(r'\s*REAL\s*,\s*DIMENSION\(kts:kte', x, re.I) and 'INTENT' not in x.upper())
    new.insert(decl, '      REAL, DIMENSION(kts:kte+1):: ' + ', '.join(THOMPSON_SHARED.values()) + '   ! shared storage (THOMPSON_SHARED in tools/gen_device_physics.py)')
    pat = re.compile(r'\b(' + '|'.join(THOMPSON_SHARED) + r')\b(?=\s*\()', re.I)
    new = [x if x.lstrip().startswith('!') else pat.sub(lambda m: THOMPSON_SHARED[m.group(1).lower()], x) for x in new]
    return out + new + lines[end + 1:]


def thompson(lines):
    lines = [s.replace('use mpas_atmphys_functions, only: gammp,wgamma,rslf,rsif', 'use mpas_atmphys_functions, only: gammp,wgamma') for s in lines]
    names = [n for n in dg.module_variables(lines) if n.lower() not in FULL_FREEZING_TABLES]   # the card holds the *_in slices
    lines = dg.inline_internal(lines, 'mp_thompson')
    lines = dg.drop_lines(lines, DEBUG_IO)
    lines = split_thompson(lines)
    lines = share_thompson_storage(lines)
    # the two saturation functions of the original module, as text copies with the device attribute
    rs = []
    for fn in ('RSLF', 'RSIF'):
        f = reference_function(fn)
        f.insert(1, ' !$acc routine seq')
        rs += f + ['']
    rs = [re.sub(r'\b(rslf|rsif)\b', lambda m: m.group(1) + '_dev', s, flags=re.I) for s in rs]
    lines = [re.sub(r'\b(rslf|rsif)\s*\(', lambda m: m.group(1) + '_dev(', s, flags=re.I) for s in lines]
    lines = dg.add_routine_seq(lines, ['mp_thompson', 'calc_effectRad'])
    lines = declare_and_update(lines, names, r'^\s*CONTAINS\s*$', r'^\s*END\s+SUBROUTINE\s+thompson_init')
    lines = dg.add_routine_seq(lines, THOMPSON_STAGES)
    lines = refl_card(lines)
    k = max(m for m, s in enumerate(lines) if dg.END_MODULE.match(s))
    return lines[:k] + rs + lines[k:]


