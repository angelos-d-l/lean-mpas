# the stops of the column code (message -> code of src/phys_fault.f90) and how many each device version must have; host-only stops stay
FAULT_CODES = {'MYNN PBL column': 1, 'MYNN surface column': 2, 'GWDO column': 3,
               'Error in ResistanceAboveCanopyMostMod.F90': 4, 'Error: ZeroPlaneDisp problem in NoahMP LSM': 5,
               'Error in ResistanceBareGroundMostMod.F90': 6, 'Error: Longwave radiation budget problem in NoahMP LSM': 7,
               'Error: Water budget problem in NoahMP LSM': 8, 'Error: Solar radiation budget problem in NoahMP LSM': 9,
               'Error: Energy budget problem in NoahMP LSM': 10}
FAULT_COUNT = {'mynn': 4, 'gwdo': 2, 'noahmp_core': 7}   # both resistance pairs are compiled


def faults(lines, name):
    """`[error] stop 'message'` of FAULT_CODES -> `call physics_fault(code)`, with `use lean_phys_fault` in the modules that now call it"""
    pat = re.compile(r'''\b(?:error\s+)?stop\s*(['"])(.*?)\1''', re.I)
    out, n = [], 0
    for s in lines:
        m = pat.search(dg.code_of(s))
        if m and m.group(2) in FAULT_CODES:
            s = s[:m.start()] + 'call physics_fault(%d)' % FAULT_CODES[m.group(2)] + s[m.end():]
            n += 1
        out.append(s)
    if n != FAULT_COUNT.get(name, 0):
        raise SystemExit('%s: %d fatal stops converted, expected %d' % (name, n, FAULT_COUNT.get(name, 0)))
    idx = [i for i, s in enumerate(out) if dg.MODULE.match(s)]
    ends = [i for i, s in enumerate(out) if dg.END_MODULE.match(s)]
    mark = {a for a, b in zip(idx, ends) if any('call physics_fault(' in out[k] for k in range(a, b))}
    res = []
    for i, s in enumerate(out):
        res.append(s)
        if i in mark:
            res.append(' use lean_phys_fault, only: physics_fault')
    return res


def reference_function(name):
    """text of a function of the pristine mpas_atmphys_functions.F (so the device copy is the same text)"""
    text = (root / 'third_party/mpas-8.4.2/src/core_atmosphere/physics/mpas_atmphys_functions.F').read_text().split('\n')
    start = next(i for i, s in enumerate(text) if re.match(r'^\s*REAL\(KIND=RKIND\)\s+FUNCTION\s+%s\b' % name, s, re.I))
    end = next(i for i in range(start, len(text)) if re.match(r'^\s*END\s+FUNCTION\s+%s\b' % name, text[i], re.I))
    return [s for s in text[start:end + 1]]


def seq_all(lines, skip=()):
    skip = {s.lower() for s in skip}
    return dg.add_routine_seq(lines, [n for n, _ in dg.module_procedures(lines) if n.lower() not in skip])


def declare_and_update(lines, names, declare_before, update_before, module=None):
    """module variables `names` live on the card: declared in the specification part, updated at the end of the initialisation routine"""
    lines = dg.insert_before(lines, declare_before, dg.acc_list('declare create', names))
    lines = dg.insert_before(lines, update_before, dg.acc_list('update device', names))
    return lines


