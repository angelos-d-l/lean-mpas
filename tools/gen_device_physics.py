def sea_ice_noah(lines):
    if any(re.match(p, dg.code_of(s), re.I) for s in lines for p in ALL_IO):
        raise SystemExit('sea_ice_noah: I/O or a stop in the sea-ice scheme')
    # ILOC and JLOC, module variables (threadprivate on the host) that SFLX_SEAICE sets from its arguments and nothing
    # reads (WRF's debug location): on the card every thread would store to the same word, so the two stores go
    uses = [i for i, s in enumerate(lines) if re.search(r'\b[ij]loc\b', dg.code_of(s), re.I)]
    sets = [i for i in uses if re.match(r'^\s*[ij]loc\s*=\s*[ij]{2}loc\s*$', dg.code_of(lines[i]), re.I)]
    decls = [i for i in uses if re.match(r'^\s*(integer\b|!\$omp\s+threadprivate)', lines[i], re.I)]
    if len(sets) != 2 or sorted(sets + decls) != uses:
        raise SystemExit('sea_ice_noah: ILOC/JLOC are read somewhere, or not where expected')
    lines = [s for i, s in enumerate(lines) if i not in sets]
    # its one fatal check (the FATAL_ERROR macro of the original, physics_error_fatal) -> the fault code of
    # src/phys_fault.f90; the host stops with the same message after the stage
    msg = "FATAL_ERROR( 'Physical snow depth is less than snow water equiv.' )"
    fatal = [i for i, s in enumerate(lines) if 'FATAL_ERROR' in dg.code_of(s) and not s.startswith('#define')]
    if len(fatal) != 1 or lines[fatal[0]].strip() != msg:
        raise SystemExit('sea_ice_noah: %d FATAL_ERROR calls, expected the one of the snow density' % len(fatal))
    lines[fatal[0]] = lines[fatal[0]].replace(msg, 'call physics_fault(sea_ice_fault)')
    use = [i for i, s in enumerate(lines) if re.match(r'^\s*use\s+mpas_atmphys_utilities\s*,\s*only\s*:\s*physics_error_fatal\s*$', s, re.I)]
    define = [i for i, s in enumerate(lines) if s.startswith('#define FATAL_ERROR')]
    if len(use) != 1 or len(define) != 1:
        raise SystemExit('sea_ice_noah: the use of physics_error_fatal or the FATAL_ERROR macro is not where expected')
    lines[use[0]] = 'use lean_phys_fault, only: physics_fault, sea_ice_fault'
    del lines[define[0]]
    return seq_all(lines)


