# ---- work-array pools ---------------------------------------------------------------------------------------------------------
# CUDA reserves the largest per-thread stack frame of the program for every thread the card can hold (for example 48 SMs x 1536
# threads), so a routine with 40 KB of column work arrays costs 3 GB of card memory although only its few resident threads use it.
# POOLED routines keep their level arrays (DIMENSION(kts:max_levels[+1])) in pools of src/device/micro_pool.f90 instead, indexed by
# the thread's slot in its launch (lean_warp thread_slot); the kernels that call them cap their grid at the pool's slots.
# pool(slot, level, array): the threads of a warp touch consecutive words, as in local memory. A routine that passes its arrays to
# others takes the 'aos' layout, pool(level, array, slot): each thread's array is contiguous, so it passes without a copy. Same
# statements, same arithmetic.
THOMPSON_POOLED_REALS = ('nifaten', 'satw', 'sati', 'delqvs', 'smod', 'vtck', 'vtnck', 'vts_boost', 'lvt2', 'smo1', 'smo0', 'smof',
                         'sed_c', 'vtnik', 'qvsi', 'smoc', 'nwfaten', 'nifa', 'tcond', 'smoe')   # its least-used reals (<= 7 references)
THOMPSON_STAGE_POOLED = []   # set by split_thompson: the level arrays that cross a stage
THOMPSON_STAGE_INDEX = {}    # set by pool_locals: name -> (pool family, field) in the stages
THOMPSON_ARGS = ['qv1d', 'qc1d', 'qi1d', 'qr1d', 'qs1d', 'qg1d', 'ni1d', 'nr1d', 'nc1d', 'nwfa1d', 'nifa1d', 't1d', 'p1d', 'w1d', 'dzq']
# the generated stages the card runs; the column parts a2, c1, c2 are cut out (they decide which arrays cross a stage) but the card
# runs them as the hand-written pieces of tools/thompson_card.f90, so they are not emitted
THOMPSON_STAGES = ['mp_thompson_a1', 'mp_thompson_b1', 'mp_thompson_b1u', 'mp_thompson_b2', 'mp_thompson_b3']
# MYNN is not pooled: on the card it runs as the hand-written stages of src/device/mynn_card.f90, and its generated
# column code (bl_mynn_run, DMP_mf) serves only the host path, with its level arrays as locals.
POOLED = {'thompson': [('mp_thompson', '', ('dl', THOMPSON_POOLED_REALS))] + [(n, '', ('', THOMPSON_STAGE_POOLED)) for n in THOMPSON_STAGES],
          'gf_core': [('CUP_gf', 'aos'), ('CUP_gf_sh', 'aos')], 'gf': [('advance_gf_columns', 'aos2')]}


# pool families: pool_pr real, pool_pd double precision, pool_pl logical (slot, level, array); pool_pq real (slot, level, n, array);
# pool_pa, pool_pb real (level, array, slot). (One named array per work array is no faster and wastes card memory in allocation
# granularity.)
# A third POOLED field limits a routine to those kinds, or (kinds, names): mp_thompson pools its double-precision rates, its
# logicals and its 20 least-used reals; its other reals stay in local memory (each pooled array costs speed: global, not local memory).
POOL_NAMES = {('r', ''): 'pr', ('p', ''): 'pr', ('d', ''): 'pd', ('l', ''): 'pl', ('r2', ''): 'pq', ('p2', ''): 'pq',
              ('r', 'aos'): 'pa', ('p', 'aos'): 'pa', ('r2', 'aos'): 'pa', ('p2', 'aos'): 'pa',
              ('r', 'aos2'): 'pb', ('p', 'aos2'): 'pb', ('r2', 'aos2'): 'pb', ('p2', 'aos2'): 'pb'}
POOL_EXTENT = {}   # pq index -> its second extent (the largest user's)


def pool_locals(lines, routine, layout='', kinds=None):
    """routine's level arrays (DIMENSION(kts|1:max_levels[+1][,1:n])) -> the shared pools of src/device/micro_pool.f90: pool_pr/pd/pl
    (real, double precision, logical; slot first) or pool_pa/pb (real, aos: level first, slot last, each thread's array contiguous).
    A second dimension 1:n takes n consecutive array indices (pool_pq). Pools are shared by routines that never hold them at the same
    time (different kernels, or called one after the other); a routine nested in another pooled routine must use the other layout."""
    aos = layout.startswith('aos')
    a = next(i for i, x in enumerate(lines) if re.match(r'^\s*subroutine\s+%s\s*\(' % routine, x, re.I))
    b = next(i for i in range(a, len(lines)) if re.match(r'^\s*end\s+subroutine\b', lines[i], re.I))
    decl_re = re.compile(r'^\s*(real\s*\(\s*(?:kind\s*=\s*)?kind_phys\s*\)|real|double precision|logical)\s*,\s*'
                         r'dimension\s*\(\s*(?:kts|1)\s*:\s*(max_levels(?:\s*\+\s*1)?)\s*(?:,\s*1\s*:\s*(\w+)\s*)?\)\s*::\s*(.*)$', re.I)
    consts = {}
    for k in range(a, b + 1):
        m = re.match(r'^\s*integer\s*,\s*parameter\s*::\s*(\w+)\s*=\s*(\d+)\s*$', lines[k], re.I)
        if m:
            consts[m.group(1).lower()] = int(m.group(2))
    names = {}   # lower name -> (family, index, extent text, second extent or None)
    used = {}
    body = []
    for k in range(a, b + 1):
        x = lines[k]
        m = decl_re.match(x)
        if m and k > a and '&' not in x:
            t0 = m.group(1).lower().replace(' ', '')
            t = 'p' if 'kind_phys' in t0 else {'real': 'r', 'doubleprecision': 'd', 'logical': 'l'}[t0]
            n2 = m.group(3)
            if kinds:
                kind_set, extra = (kinds, ()) if isinstance(kinds, str) else kinds
                if t not in kind_set:
                    sel = [y.strip() for y in m.group(4).split(',') if y.strip() and y.strip().lower() in extra]
                    rest = [y.strip() for y in m.group(4).split(',') if y.strip() and y.strip().lower() not in extra]
                    if not sel:
                        body.append(x)
                        continue
                    if rest:   # the declaration keeps the arrays that stay in local memory
                        body.append(x[:x.index('::') + 2] + ' ' + ', '.join(rest))
                    m = decl_re.match(x[:x.index('::') + 2] + ' ' + ', '.join(sel))
            if n2 and aos and n2 != '1':
                raise SystemExit('pool %s: aos arrays with a second dimension other than 1:1' % routine)
            fam = POOL_NAMES[(t + ('2' if n2 else ''), layout)]
            for n in [y.strip() for y in m.group(4).split(',') if y.strip()]:
                used[fam] = used.get(fam, 0) + 1
                names[n.lower()] = (fam, used[fam], m.group(2).replace(' ', ''), n2)
                if fam == 'pq':
                    w = int(n2) if n2.isdigit() else consts[n2.lower()]
                    POOL_EXTENT[used[fam]] = max(POOL_EXTENT.get(used[fam], 0), w)
            continue
        body.append(x)
    if not names:
        raise SystemExit('pool %s: no level arrays' % routine)
    decl = re.compile(r'^\s*(integer|real|double|logical|character|type\s*\(|parameter|data|dimension|save|intrinsic|external|implicit|use\b|!\$acc)', re.I)
    first = None
    for k in range(1, len(body)):
        c = dg.code_of(body[k]).strip()
        if not c or c.startswith('&') or c.startswith('#') or decl.match(c) or dg.code_of(body[k - 1]).rstrip().endswith('&'):
            continue
        first = k
        break
    # an #ifdef block opened just before (its declarations above): the slot goes before the block
    while first > 1 and body[first - 1].strip().startswith('#') and not body[first - 1].strip().startswith('#endif'):
        first -= 1
    pat = re.compile(r'(?<![%\w])(' + '|'.join(sorted((re.escape(n) for n in names), key=len, reverse=True)) + r')\b', re.I)

    def sub(code):
        out, i = '', 0
        for m in pat.finditer(code):
            if m.start() < i:
                continue
            fam, idx, ext, n2 = names[m.group(1).lower()]
            arr = 'pool_' + fam
            j = m.end()
            k = j
            while k < len(code) and code[k] == ' ':
                k += 1
            if k < len(code) and code[k] == '(':
                e = dg._match_fwd(code, k)
                args = [x.strip() for x in dg.split_top(sub(code[k + 1:e]))]
                if fam in ('pa', 'pb'):
                    # a 1:1 second dimension: any in-bounds subscript is 1 (CUP_gf's ensemble index iedt runs 1..1)
                    r = '%s(%s,%d,slot_)' % (arr, args[0], idx)
                else:
                    r = '%s(slot_,%s,%d)' % (arr, ','.join(args), idx)
                j = e + 1
            else:
                if fam in ('pa', 'pb'):
                    r = '%s(1:%s,%d,slot_)' % (arr, ext, idx)
                elif n2:
                    r = '%s(slot_,1:%s,1:%s,%d)' % (arr, ext, n2, idx)
                else:
                    r = '%s(slot_,1:%s,%d)' % (arr, ext, idx)
            out += code[i:m.start()] + r
            i = j
        return out + code[i:]
    for k in range(1, len(body)):
        x = body[k]
        if k < first and decl.match(dg.code_of(x).strip()):
            continue
        code, rest = (x.split('!', 1)[0], '!' + x.split('!', 1)[1]) if '!' in x and not x.strip().startswith('!$') else (x, '')
        if code.strip():
            body[k] = sub(code) + rest
    # the two lines go before a preprocessor block that opens right before the first executable line (gf's LEAN_GF_DXMIN block):
    # inside it, a build without that switch would have no slot_ and would not compile
    at = first
    while at > 0 and (not body[at - 1].strip() or (body[at - 1].strip().startswith('!') and not body[at - 1].strip().startswith('!$'))):
        at -= 1
    while at > 0 and body[at - 1].lstrip().startswith('#if'):
        at -= 1
    if at == first or not body[at].lstrip().startswith('#if'):
        at = first
    body[at:at] = ['      integer :: slot_', '      slot_ = thread_slot()   ! the work arrays of this thread in the pools of src/device/micro_pool.f90']
    hdr = dg.header_end(body, 0)
    body[hdr + 1:hdr + 1] = ['      use micro_pool, only: ' + ', '.join('pool_' + f for f in sorted(used)),
                             '      use lean_warp, only: thread_slot']
    print('pool %s: %d level arrays (%s)' % (routine, len(names), ', '.join('%s %d' % (p, used[p]) for p in sorted(used))))
    for p in used:
        POOL_USERS.setdefault(p, []).append(routine)
    if routine in THOMPSON_STAGES:   # the hand-written stages (THOMPSON_CARD_FILE) name the fields (tp_*, td_*, tl_* in micro_pool)
        for n, (fam, idx, ext, n2) in names.items():
            if THOMPSON_STAGE_INDEX.setdefault(n, (fam, idx)) != (fam, idx):
                raise SystemExit('pool %s: %s is not where the other stages have it' % (routine, n))
    return lines[:a] + body + lines[b + 1:], used

def pool_module():
    """src/device/micro_pool.f90: the pools of the POOLED routines, sized for the largest user of each family"""
    n = {f: POOL_SIZES.get(f, 0) for f in ('pr', 'pd', 'pl', 'pq', 'pa', 'pb')}
    w = max(POOL_EXTENT.values()) if POOL_EXTENT else 1
    kind = {'pr': 'real', 'pd': 'double precision', 'pl': 'logical', 'pq': 'real', 'pa': 'real', 'pb': 'real'}
    dims = {'pr': '(slot, level, array)', 'pd': '(slot, level, array)', 'pl': '(slot, level, array)',
            'pq': '(slot, level, n, array)', 'pa': '(level, array, slot)', 'pb': '(level, array, slot)'}
    t = ['! GENERATED by tools/gen_device_physics.py (the POOLED routines of src/thompson.f90, src/gf_core.f90, src/gf.f90) - do not edit.',
         '! The work-array pools of the card\'s pooled column routines; compiled in every build, allocated only by the card build. CUDA',
         '! reserves the largest per-thread stack frame of the program for every thread the card can hold (for example 48 SMs x 1536',
         '! threads), so a column routine with 40 KB of level arrays costs 3 GB of card memory although only its resident threads use it.',
         '! A pooled routine keeps those arrays here, indexed by the thread\'s slot in its launch (lean_warp thread_slot); its kernel caps',
         '! the grid at the pool\'s slots. A pool is shared by routines that never hold it at the same time (different kernels, or called',
         '! one after the other). In the (level, array, slot) layout each thread\'s array is contiguous, so it passes without a copy.']
    groups = {}   # the families with the same users on one line
    for f in n:
        if n[f]:
            groups.setdefault((tuple(POOL_USERS[f]), dims[f]), []).append(f)
    for (users, shape), fams in groups.items():
        t.append('!   %s %s: %s' % (', '.join('pool_%s %s' % (f, kind[f]) for f in fams), shape, ', '.join(users)))
    t += ['module micro_pool',
         ' use config, only: max_levels',
         ' implicit none',
         ' private',
         ' public :: pool_slots, pool_slots2, micro_pool_allocate, micro_pool_start, pool_bytes, pool_staged',
         ' public :: ' + ', '.join('pool_' + f for f in n if n[f]) + ', pool_mc, n_mc',
         ' integer, parameter :: ' + ', '.join('n_%s = %d' % (f, n[f]) for f in n) + ', w_pq = %d' % w]
    decl = {'pr': 'real', 'pd': 'double precision', 'pl': 'logical', 'pq': 'real', 'pa': 'real', 'pb': 'real'}
    rank = {'pr': '(:,:,:)', 'pd': '(:,:,:)', 'pl': '(:,:,:)', 'pq': '(:,:,:,:)', 'pa': '(:,:,:)', 'pb': '(:,:,:)'}
    for f in n:
        if n[f]:
            t.append(' %s, allocatable, save :: pool_%s%s' % (decl[f], f, rank[f]))
    t += [' ! the column arrays of the Thompson stages (src/dyn_micro.f90 micro_staged), slot first: fields 1-15',
          ' ! the column arguments of mp_thompson (THOMPSON_ARGS), 16 theta, 17 rho of micro_cell',
          ' integer, parameter :: n_mc = 17', ' real, allocatable, save :: pool_mc(:,:,:)']
