# ---- Noah-MP: every procedure of the closure is device code; the fatal-error reports (write, stop) cannot run on the card --------
def noahmp_state_dev(lines):
    """pointer assignments with a lower bound (a%x(-2:) => state%x(:,c)) are not available in device code (runtime function): a lower bound of 1 is
    the default, the others go through a helper that takes the column as an explicit-shape dummy with those bounds"""
    # the members are allocatable: their types are in the type body, their bounds in allocate_land
    lines = dg.insert_before(lines, r'^\s*contains\s*$', [' !$acc declare create(noahmp_opt_sfc)'])
    decl = {}
    types = {}
    in_state = False
    for s in lines:
        if re.match(r'^\s*type\s+noahmp_state_type\s*$', s, re.I):
            in_state = True
        elif in_state and re.match(r'^\s*end\s*type', s, re.I):
            in_state = False
        elif in_state:
            m = re.match(r'^\s*(real\(kind=kind_noahmp\)|integer|logical)\s*,\s*allocatable\s*::\s*(\w+)\(:,:\)\s*$', s, re.I)
            if m:
                types[m.group(2).lower()] = m.group(1).lower()
        else:
            m = re.match(r'^\s*allocate\(s%(\w+)\((-?\d+):(\d+),ncells\)\)\s*$', s, re.I)
            if m:
                decl[m.group(1).lower()] = (types[m.group(1).lower()], int(m.group(2)), int(m.group(3)))
    helpers = {}
    out = []
    for s in lines:
        m = re.match(r'^(\s*)a%(\w+)\((-?\d+):\)\s*=>\s*state%(\w+)\(:,c\)\s*$', s, re.I)
        if m:
            ind, n, lb = m.group(1), m.group(2), int(m.group(3))
            if lb == 1:
                s = '%sa%%%s => state%%%s(:,c)' % (ind, n, n)
            else:
                typ, dlb, dub = decl[n.lower()]
                assert dlb == lb, n
                key = ('r' if typ.startswith('real') else 'i' if typ == 'integer' else 'l', lb, dub)
                helpers[key] = typ
                s = '%scall lbp_%s_%s_%d(a%%%s, state%%%s(:,c))' % (ind, key[0], ('m%d' % -lb) if lb < 0 else str(lb), dub, n, n)
        out.append(s)
    out = dg.add_routine_seq(out, ['noahmp_view'])
    # the view also carries the state and the column index, so that update_land can call the Noah-MP of the card
    # (gen_device_physics.deview) with them; the view type moves after noahmp_state_type for its pointer component
    a = next(i for i, s in enumerate(out) if re.match(r'^\s*type\s+noahmp_column\s*$', s, re.I))
    b = next(i for i in range(a, len(out)) if re.match(r'^\s*end\s*type', out[i], re.I))
    view = out[a:b] + ['  type(noahmp_state_type), pointer :: state_   ! the state and column of this view',
                       '  integer :: c_'] + [out[b]]
    del out[a:b + 1]
    e = next(i for i, s in enumerate(out) if re.match(r'^\s*type\s+noahmp_state_type\s*$', s, re.I))
    e = next(i for i in range(e, len(out)) if re.match(r'^\s*end\s*type', out[i], re.I))
    out[e + 1:e + 1] = view
    f = next(i for i, s in enumerate(out) if re.match(r'^\s*end\s*function\b', s, re.I) and
             any(re.match(r'^\s*function\s+noahmp_view\b', out[k], re.I) for k in range(max(0, i - 600), i)))
    out[f:f] = [' a%state_ => state', ' a%c_ = c']
    new = []
    for (k, lb, ub), typ in helpers.items():
        nm = 'lbp_%s_%s_%d' % (k, ('m%d' % -lb) if lb < 0 else str(lb), ub)
        new += [' subroutine %s(p, arr)' % nm, ' !$acc routine seq', ' %s, pointer, intent(inout) :: p(:)' % typ,
                ' %s, target, intent(in) :: arr(%d:%d)' % (typ, lb, ub), ' p => arr', ' end subroutine']
    j = max(i for i, s in enumerate(out) if dg.END_MODULE.match(s))
    return out[:j] + new + out[j:]


def noahmp_fields():
    """field -> None (one value per cell) or 'lb:ub' (first dimension) of noahmp_state_type (src/noahmp_state.f90)"""
    text = (root / 'src' / 'noahmp_state.f90').read_text()
    body = re.search(r'^\s*subroutine\s+allocate_land\b(.*?)^\s*end\s*subroutine', text, re.I | re.M | re.S).group(1)
    fields = {}
    for m in re.finditer(r'allocate\(s%(\w+)\(([^)]*)\)\)', body):   # the bounds are those of allocate_land
        dims = m.group(2).replace(' ', '')
        fields[m.group(1).lower()] = None if dims == 'ncells' else dims.split(',')[0]
    return fields


def direct_ref(v, field, sub, fields):
    """the column element of noahmp_state_type for v%field[(sub)]: the column index is the dummy v_c"""
    if fields[field.lower()] is None:
        if sub is not None:
            raise SystemExit('subscript on the scalar field %s' % field)
        return '%s%%%s(%s_c)' % (v, field, v)
    return '%s%%%s(%s, %s_c)' % (v, field, sub if sub is not None else ':', v)


def rewrite_refs(code, pattern, target, fields):
    """every match of `pattern` (a name not preceded by % or a word character) -> direct_ref, with its subscripts if any (same line)"""
    out, i = '', 0
    for m in pattern.finditer(code):
        if m.start() < i:
            continue
        v, field = target(m)
        j = m.end()
        k = j
        while k < len(code) and code[k] == ' ':
            k += 1
        sub = None
        if k < len(code) and code[k] == '(':
            e = dg._match_fwd(code, k)
            sub = rewrite_refs(code[k + 1:e], pattern, target, fields)   # names inside the subscripts too
            j = e + 1
        out += code[i:m.start()] + direct_ref(v, field, sub, fields)
        i = j
    return out + code[i:]


def deview(lines, v):
    """Noah-MP on the card without the column view. The view is 458 pointers (14 KB per thread, in local memory) and every field access
    first loads its pointer from there; with tens of thousands of threads that misses every cache (through the view the land stage on the
    card is slower than on one CPU core). Here a routine whose column dummy is `v` (type noahmp_column) gets the state and the column
    index instead, `(v, v_c)` with v of noahmp_state_type, and every field is the element itself: associate names bound to v%field are
    replaced by v%field(v_c) / v%field(sub, v_c) / v%field(:, v_c) (the declared bounds, e.g. -2:4, stay those of the state array), the
    direct v%field references the same, and the calls that pass v pass v, v_c. Same arithmetic, same order."""
    fields = noahmp_fields()
    out = list(lines)
    # 1. associate blocks: the entries bound to v%field are substituted in the block and removed from the statement
    i = 0
    while i < len(out):
        if re.match(r'^\s*associate\s*\(', dg.code_of(out[i]), re.I):
            e = dg.header_end(out, i)
            text = ' '.join(dg.code_of(out[k]).strip().rstrip('&').lstrip('&').strip() for k in range(i, e + 1))
            ind = re.match(r'^(\s*)', out[i]).group(1)
            inner = text[text.index('(') + 1:text.rindex(')')]
            keep, alias = [], {}
            const = {}
            for ent in dg.split_top(inner):
                m = re.match(r'^\s*(\w+)\s*=>\s*%s%%(\w+)\s*$' % v, ent, re.I)
                k = re.match(r'''^\s*(\w+)\s*=>\s*(\d+|'[^']*'|\.(?:true|false)\.)\s*$''', ent, re.I)
                if m:
                    if m.group(2).lower() not in fields:
                        raise SystemExit('unknown Noah-MP field %s' % m.group(2))
                    alias[m.group(1).lower()] = m.group(2)
                elif k:
                    # an associate name for a constant is a temporary that the card compiler allocates with malloc (and frees) at every
                    # entry of the block: device malloc is serialised over the whole card. The constant itself goes in its place.
                    const[k.group(1).lower()] = k.group(2)
                else:
                    keep.append(ent.strip())
            # the matching end associate
            d, j = 0, e + 1
            while True:
                c = dg.code_of(out[j])
                if re.match(r'^\s*associate\s*\(', c, re.I):
                    d += 1
                elif re.match(r'^\s*end\s*associate\b', c, re.I):
                    if d == 0:
                        break
                    d -= 1
                j += 1
            if const:
                cpat = re.compile(r'(?<![%\w])(' + '|'.join(sorted(const, key=len, reverse=True)) + r')\b(?!\s*=>)', re.I)
                for k in range(e + 1, j):
                    s = out[k]
                    code, rest = (s.split('!', 1)[0], '!' + s.split('!', 1)[1]) if '!' in s else (s, '')
                    out[k] = cpat.sub(lambda m: const[m.group(1).lower()], code) + rest
            if alias:
                pat = re.compile(r'(?<![%\w])(' + '|'.join(sorted(alias, key=len, reverse=True)) + r')\b(?!\s*=>)', re.I)
                for k in range(e + 1, j):
                    s = out[k]
                    code, rest = (s.split('!', 1)[0], '!' + s.split('!', 1)[1]) if '!' in s else (s, '')
                    if code.strip():
                        out[k] = rewrite_refs(code, pat, lambda m: (v + '__DV__', alias[m.group(1).lower()]), fields) + rest
            if keep:
                new = [ind + 'associate( ' + keep[0] + (' , &' if len(keep) > 1 else ' )')]
                new += [ind + '  & ' + x + (' , &' if n < len(keep) - 2 else ' )') for n, x in enumerate(keep[1:])]
                out[i:e + 1] = new
                i += len(new)
            else:
                del out[j]
                del out[i:e + 1]
            continue
        i += 1
    # 2. direct references v%field
    pat = re.compile(r'(?<![%\w])' + v + r'%(\w+)', re.I)
    for k, s in enumerate(out):
        code, rest = (s.split('!', 1)[0], '!' + s.split('!', 1)[1]) if '!' in s else (s, '')
        if pat.search(code):
            out[k] = rewrite_refs(code, pat, lambda m: (v, m.group(1)), fields) + rest
    out = [s.replace(v + '__DV__%', v + '%').replace(v + '__DV___c', v + '_c') for s in out]   # (the direct-reference pass left the substituted names alone)
    # 3. the dummy, the headers and the calls
    n_decl = 0
    for k, s in enumerate(out):
        m = re.match(r'^(\s*)type\s*\(\s*noahmp_column\s*\)\s*,\s*intent\s*\(\s*inout\s*\)\s*::\s*%s\s*$' % v, s, re.I)
        if m:
            out[k] = '%stype(noahmp_state_type), intent(inout) :: %s\n%sinteger, intent(in) :: %s_c' % (m.group(1), v, m.group(1), v)
            n_decl += 1
    n_head = n_call = 0
    for k, s in enumerate(out):
        c = dg.code_of(s)
        if dg.SUB.match(c) and re.search(r'\(\s*%s\s*[,)]' % v, c, re.I):
            out[k] = re.sub(r'\(\s*%s\s*([,)])' % v, r'(%s, %s_c\1' % (v, v), s, count=1, flags=re.I)
            n_head += 1
        elif re.match(r'^\s*(?:if\s*\(.*\)\s*)?call\s+\w+\s*\(\s*%s\s*[,)]' % v, c, re.I):
            out[k] = re.sub(r'(call\s+\w+\s*)\(\s*%s\s*([,)])' % v, r'\1(%s, %s_c\2' % (v, v), s, count=1, flags=re.I)
            n_call += 1
    if n_decl != n_head:
        raise SystemExit('deview %s: %d column dummies, %d headers' % (v, n_decl, n_head))
    text = '\n'.join(out)
    left = re.findall(r'(?<![%\w])' + v + r'(?![\w%(])(?!_c)', '\n'.join(dg.code_of(s) for s in text.split('\n')
                                                                           if not re.match(r'^\s*(type|integer)\b', s, re.I)))
    if any(True for _ in left) and n_call == 0 and n_head == 0:
        raise SystemExit('deview %s: nothing changed' % v)
    print('deview %s: %d routines, %d calls' % (v, n_head, n_call))
    return text.split('\n')


