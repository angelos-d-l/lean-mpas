def tridiag_work(lines):
    """tridiag2's work arrays cp, dp come from its callers (mym_predict, mynn_tendencies) as two more arguments.
    On the card (nvfortran 25.3) tridiag2 is inlined into mynn_tendencies, and with a run-time level count its own cp, dp get the
    local-memory slots of the caller's kmdz, khdz while those are still to be read, so the v, theta and moisture solves after the
    u solve would use tridiag2's leftovers. A callee without local arrays leaves nothing to overlap."""
    def one(pattern, new, count):
        nonlocal lines
        hits = [k for k, s in enumerate(lines) if re.match(pattern, s, re.I)]
        if len(hits) != count:
            raise SystemExit('tridiag_work: %d lines match %s (expected %d)' % (len(hits), pattern, count))
        for k in hits:
            lines[k] = new(lines[k])
        return hits
    lines = list(lines)
    one(r'^\s*subroutine\s+tridiag2\(a,b,c,d,x\)\s*$', lambda s: s.replace('(a,b,c,d,x)', '(a,b,c,d,x,cp,dp)'), 1)
    one(r'^\s*real\(kind_phys\), dimension\(n\) ::cp,dp\s*$', lambda s: s.replace('dimension(n) ::', 'dimension(n), intent(out) ::'), 1)
    calls = one(r'^\s*call tridiag2\(a,b,c,d,\w+\)\s*$', lambda s: s.rstrip()[:-1] + ',tri_cp,tri_dp)', 8)
    # one declaration of the work arrays in each calling routine, next to its a, b, c, d, x
    starts = [k for k, s in enumerate(lines) if re.match(r'^\s*SUBROUTINE\s+(mym_predict|mynn_tendencies)\b', s, re.I)]
    decls = one(r'^\s*real\(kind_phys\), dimension\(kts:kte\) ::a,b,c,d,x\s*$', lambda s: s, 2)
    if len(starts) != 2 or not all(starts[i] < decls[i] < (starts[i+1] if i + 1 < 2 else len(lines)) for i in range(2)) \
            or not all(any(starts[i] < c < (starts[i+1] if i + 1 < 2 else len(lines)) for c in calls) for i in range(2)):
        raise SystemExit('tridiag_work: the callers of tridiag2 are not mym_predict and mynn_tendencies')
    for k in reversed(decls):
        lines.insert(k + 1, re.match(r'^\s*', lines[k])[0] + 'real(kind_phys), dimension(kts:kte) ::tri_cp,tri_dp')
    return lines


