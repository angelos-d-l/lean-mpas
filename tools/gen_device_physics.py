# ---- Grell-Freitas -------------------------------------------------------------------------------------------------------------
# cup_kbcon's search loop as the original writes it (GO TO 31 back, GO TO 32 forward, GO TO 27 out of the one-column DO 27). On the card
# (nvfortran 25.3, -O2) the KBCON > KBMAX+2 exits of this loop are not taken: KBCON runs past KBMAX+2 to kte+1 and kte+2 with ierr still 0
# (seen in many columns per step on the card, in none on the host from the same file), so HES_cup is read beyond kte and
# the result depends on what lies there (the next local array with exact sizes, an unset capacity slot with max_levels). The same logic in
# DO/EXIT/CYCLE form compiles right; on the host it is the same algorithm, so only the device version takes it.
KBCON_GOTO = '''    DO 27 i=its,itf
      kbcon=1
      IF(ierr.ne.0)GO TO 27
      KBCON=K22+1
      if(iloop.eq.5)KBCON=K22
      GO TO 32
      31 CONTINUE
      KBCON=KBCON+1
      IF(KBCON.GT.KBMAX+2)THEN
        if(iloop.ne.4)then
          ierr=3
          ierrc="could not find reasonable kbcon in cup_kbcon"
        endif
        GO TO 27
      ENDIF
      32 CONTINUE
      hetest=hkb
      if(iloop.eq.5)then
        hetest=HKB
      endif
      IF(HETEST.LT.HES_cup(KBCON))then
        GO TO 31
      endif
      if(KBCON-K22.eq.1)go to 27
      if(iloop.eq.5 .and. (KBCON-K22).eq.0)go to 27
      PBCDIF=-P_cup(KBCON)+P_cup(K22)
      plus=max(25.,cap_max-float(iloop-1)*cap_inc)
      if(iloop.eq.4)plus=cap_max
      if(iloop.eq.5)plus=25.
      if(iloop.eq.5.and.cap_max.gt.25)pbcdif=-P_cup(KBCON)+cap_max
      IF(PBCDIF.GT.plus)THEN
        K22=K22+1
        KBCON=K22+1
        if(use_excess == 2) then
          k1=max(1,k22-1)
          k2=max(1,min(kbcon-1,k22+1))
          k2=k22+1
          hkb=sum(he_cup(k1:k2))/float(k2-k1+1)+(xl*zqexec+cp*ztexec)/float(k2-k1+1)
        else if(use_excess <= 1)then
          hkb=he_cup(k22)+float(use_excess)*(xl*zqexec+cp*ztexec)
        endif
        if(iloop.eq.5)KBCON=K22
        IF(KBCON.GT.KBMAX+2)THEN
          if(iloop.ne.4)then
            ierr=3
            ierrc="could not find reasonable kbcon in cup_kbcon"
          endif
          GO TO 27
        ENDIF
        GO TO 32
      ENDIF
    27 CONTINUE'''
KBCON_LOOP = '''    do i=its,itf
      kbcon=1
      if(ierr.ne.0)cycle
      KBCON=K22+1
      if(iloop.eq.5)KBCON=K22
      do
        hetest=hkb
        if(iloop.eq.5)then
          hetest=HKB
        endif
        IF(HETEST.LT.HES_cup(KBCON))then
          KBCON=KBCON+1
          IF(KBCON.GT.KBMAX+2)THEN
            if(iloop.ne.4)then
              ierr=3
              ierrc="could not find reasonable kbcon in cup_kbcon"
            endif
            exit
          ENDIF
          cycle
        endif
        if(KBCON-K22.eq.1)exit
        if(iloop.eq.5 .and. (KBCON-K22).eq.0)exit
        PBCDIF=-P_cup(KBCON)+P_cup(K22)
        plus=max(25.,cap_max-float(iloop-1)*cap_inc)
        if(iloop.eq.4)plus=cap_max
        if(iloop.eq.5)plus=25.
        if(iloop.eq.5.and.cap_max.gt.25)pbcdif=-P_cup(KBCON)+cap_max
        IF(.not.(PBCDIF.GT.plus))exit
        K22=K22+1
        KBCON=K22+1
        if(use_excess == 2) then
          k1=max(1,k22-1)
          k2=max(1,min(kbcon-1,k22+1))
          k2=k22+1
          hkb=sum(he_cup(k1:k2))/float(k2-k1+1)+(xl*zqexec+cp*ztexec)/float(k2-k1+1)
        else if(use_excess <= 1)then
          hkb=he_cup(k22)+float(use_excess)*(xl*zqexec+cp*ztexec)
        endif
        if(iloop.eq.5)KBCON=K22
        IF(KBCON.GT.KBMAX+2)THEN
          if(iloop.ne.4)then
            ierr=3
            ierrc="could not find reasonable kbcon in cup_kbcon"
          endif
          exit
        ENDIF
      enddo
    enddo'''


def kbcon_loop(lines):
    """cup_kbcon's GO TO loop -> DO/EXIT/CYCLE (see KBCON_GOTO); fails if the source text is not the one this rule was written for"""
    text = '\n'.join(lines)
    if text.count(KBCON_GOTO) != 1:
        raise SystemExit('gf_core: the GO TO loop of cup_kbcon is not the expected text (tools/gen_device_physics.py KBCON_GOTO)')
    return text.replace(KBCON_GOTO, KBCON_LOOP).split('\n')


