"""Writes the device versions of the lean physics sources into src/device/ (same module and routine names as src/, so the
OpenACC build only swaps the file; the CPU builds keep using src/ unchanged), and src/device/micro_pool.f90, the card's work-array
pools of the pooled column routines.

  python3 tools/gen_device_physics.py            regenerate all
  python3 tools/gen_device_physics.py --check    write nothing; print DIFFERS <path> for each file of src/device/ that differs, exit 1
  python3 tools/gen_device_physics.py NAME ...   only these

What changes in a device version (tools/devgen.py): internal procedures are inlined, `!$acc routine seq` is added to the column routines,
module tables get `!$acc declare create` (and an `update device` at the end of the initialisation), debug-only I/O is removed, and the
fatal stops of the column code become `call physics_fault(code)` (src/phys_fault.f90; the host stops after the stage). Thompson
and Grell-Freitas get the card-specific rewrites described where they are made (stages, pools, the cup_kbcon loop). The device
Thompson also takes RSLF and RSIF from third_party/mpas-8.4.2 mpas_atmphys_functions.F and the hand-written stages of
tools/thompson_card.f90.
"""
