MALLOC_NOTE = 'the card compiler makes the array statement with pointer operands a temporary from device malloc (serialised over the card)'


def replace_once(lines, pattern, new_lines):
    """the one line matching `pattern` -> new_lines (statements that would need a device malloc)"""
    k = [i for i, s in enumerate(lines) if re.match(pattern, s, re.I)]
    if len(k) != 1:
        raise SystemExit('%d lines match %s' % (len(k), pattern))
    return lines[:k[0]] + new_lines + lines[k[0] + 1:]


