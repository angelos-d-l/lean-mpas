"""Writes src/phys_check.f90, the bit-for-bit comparison of two copies of each physics state type (model_state, gf_state,
gwdo_state, noahmp_state): the card's copy against the host's. One compare_report call per member, from the type definitions in src/.

    python3 tools/gen_phys_check.py [--check]

--check writes nothing and exits 1 with `DIFFERS src/phys_check.f90`."""
import re, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
import devgen as dg
root = Path(__file__).resolve().parents[1]
TYPES = [('state', 'state_type', 'model_state', 'check_state'), ('gf_state', 'gf_state_type', 'gf_state', 'check_gf'),
         ('gwdo_state', 'gwdo_state_type', 'gwdo_state', 'check_gwdo'), ('noahmp_state', 'noahmp_state_type', 'noahmp_state', 'check_land')]
# The two Noah-MP members that only the Chen97 surface-resistance option (noahmp_opt_sfc == 2) uses: a restart carries
# them only with that option (tools/gen_restart_set.py), and the default member list leaves them out (gen_phys_state.py).
SFC2_FIELDS = ('energy_state_frictionvelvertveg', 'energy_state_frictionvelvertbare')
TYPE = r'(real(?:\s*\(\s*kind\s*=\s*\w+\s*\))?|integer|logical)'
DECL = re.compile(r'^' + TYPE + r'\s*(,\s*allocatable)?\s*::\s*(.*)$', re.I)


def fields(path, tname):
    """The body of type tname in path, in declaration order: a '#...' line of a build switch as it is, and for each member
    {name, type (as declared), rank (0: a scalar), allocatable}. Shared with tools/gen_phys_state.py."""
    lines = path.read_text().split('\n')
    i = next(k for k, s in enumerate(lines) if re.match(r'^\s*type\s+%s\s*$' % tname, s, re.I))
    out = []
    j = i + 1
    while not re.match(r'^\s*end\s*type', lines[j], re.I):
        stmt = dg.code_of(lines[j]).strip()
        if lines[j].startswith('#'):   # a build-switch line (#ifdef/#else/#endif) stays around its members
            out.append(lines[j])
        m = DECL.match(stmt)
        if m:
            for part in dg.split_top(m.group(3)):
                part = part.split('=', 1)[0]
                nm = re.match(r'\s*(\w+)\s*(\(.*\))?\s*$', part)
                assert nm, part
                rank = len(dg.split_top(nm.group(2)[1:-1])) if nm.group(2) else 0
                out.append({'name': nm.group(1), 'type': m.group(1), 'rank': rank, 'allocatable': bool(m.group(2))})
        j += 1
    return out


def members(path, tname):
    """the switch lines and the names of the arrays; scalars (the step counter) are not compared"""
    return [f if isinstance(f, str) else f['name'] for f in fields(path, tname) if isinstance(f, str) or f['rank'] > 0]


def main():
    out = ['! GENERATED by tools/gen_phys_check.py from the type definitions in src/ - do not edit.',
           '! Bit-for-bit comparison of two copies of each physics state type (the card\'s copy against the host\'s).',
           'module phys_check', ' use check_util', ' use model_state, only: state_type', ' use gf_state, only: gf_state_type',
           ' use gwdo_state, only: gwdo_state_type', ' use noahmp_state, only: noahmp_state_type', ' implicit none', 'contains']
    for fname, tname, mod, sub in TYPES:
        names = members(root / 'src' / (fname + '.f90'), tname)
        out += [' subroutine %s(prefix, a, b)' % sub, ' character(*), intent(in) :: prefix',
                ' type(%s), intent(in) :: a, b' % tname]
        for n in names:
            out.append(n if n.startswith('#') else " call compare_report(prefix//'%s', a%%%s, b%%%s)" % (n, n, n))
        out.append(' end subroutine')
    out.append('end module')
    text = '\n'.join(out) + '\n'
    path = root / 'src' / 'phys_check.f90'
    if '--check' in sys.argv:
        if not path.exists() or path.read_text() != text:
            print('DIFFERS src/phys_check.f90')
            return 1
        return 0
    path.write_text(text)
    print('wrote src/phys_check.f90')
    return 0


if __name__ == '__main__':
    sys.exit(main())
