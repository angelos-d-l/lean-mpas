#!/usr/bin/env python3
"""Writes docs/fields.md: every field MPAS 8.4.2 can write, with its dimensions and units from the field catalog
(MPAS 8.4.2's Registry.xml in reference/mpas_src, ./lean fetch-upstream) and where lean_mpas takes its values from
(field_class in src/lean_fields.f90).

    python3 tools/gen_fields_doc.py [--check]

Prints FIELDS DOC OK; --check writes nothing and exits 1 with FIELDS DOC STALE when the file differs."""
import argparse
from pathlib import Path
import sys
sys.path.insert(0,str(Path(__file__).resolve().parents[1]))
from tools.gen_field_catalog import load as catalog, ROOT
from tools.field_classes import load
OUT=ROOT/'docs/fields.md'
SOURCES={
 'SOURCE_TIME':'Run clock', 'SOURCE_MESH':'Mesh or static input',
 'SOURCE_STATE':'Model state', 'SOURCE_OUTPUT_DIAG':'Output conversion of model state',
 'SOURCE_LEAN':'Physics or retained input', 'SOURCE_HELD':'Input value or Registry default; held',
 'SOURCE_DIAG':'MPAS diagnostic', 'SOURCE_NONE':'Stops at start when requested by an active output stream',
}
def document():
    table=catalog();classes=load(ROOT/'src/lean_fields.f90')
    lines=['<!-- Generated by tools/gen_fields_doc.py from the field catalog and src/lean_fields.f90; do not edit. -->','# Fields written by lean_mpas','',
      'Names, dimensions and units come from the MPAS Registry catalog. Sources come from `field_class` in `src/lean_fields.f90`.',
      'An unsupported field in an active output stream stops initialization before any output file opens. The restart stream is exempt. Inactive packages remove their fields before this check.','',
      'Isobaric and convective diagnostics run on the host when a stream writes them, from the state at that time. The three convective maxima update every step and reset whenever a stream carrying them writes. Reflectivity and relative humidity update on MPAS’s `l_diags` steps. A more frequent user stream holds the last such values. `refl10cm_1km_max` resets only when the stream named `diagnostics` writes.','',
      'At regional boundary vertices, the outside cell has zero pressure. On all 344 boundary vertices of the greece_60km case (`cases/greece_60km`), this reproduces MPAS’s t=0 `vorticity_500hPa` exactly; omitting the outside cell and renormalizing differs at all 344. The vertex pressure sum follows `cellsOnVertex` slot order (MPAS `mpas_isobaric_diagnostics.F:631-642`). Updraft helicity instead follows MPAS’s first-met vertex order, as recorded in `docs/fixes.md`.','',
      'The coordinate arrays `t_iso_levels` and `z_iso_levels` start at the Registry default zero, are set when `t_isobaric` or `z_isobaric` is computed, and are held otherwise (MPAS `mpas_isobaric_diagnostics.F:562-584`).', '',
      '`t_isobaric` and `meanT_500_300` initialize temperature even when requested alone, fixing MPAS’s unset temporary. `lcl` and `lfc` retain their input values or the Registry default zero: MPAS never computes them for this suite. The seven ocean mixed-layer fields, precipitation bucket counters and unforced aerosol fields are held. `docs/fixes.md` gives the precipitable-water fix (`LEAN_PRECIPW_MOIST`) and the diagnostics alarm of a stream without a time interval.','',
      '| Field | Dimensions (fastest first) | Units | Source |','|---|---|---|---|']
    for v in table.variables:
        attrs=dict((k,value) for k,value,_ in table.attributes[v.first-1:v.first-1+v.count])
        dims=v.dims or 'scalar'
        if v.time:dims+='; Time'
        unit=attrs.get('units','').replace('|','\\|').replace('\n',' ')
        lines.append(f'| `{v.name}` | {dims} | {unit} | {SOURCES[classes.get(v.name,"SOURCE_NONE")]} |')
    return '\n'.join(lines)+'\n'
def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');args=p.parse_args()
    text=document()
    if args.check:
        if not OUT.exists() or OUT.read_text()!=text:raise SystemExit('FIELDS DOC STALE: run python3 tools/gen_fields_doc.py')
    else:OUT.write_text(text)
    print('FIELDS DOC OK')
if __name__=='__main__':main()
