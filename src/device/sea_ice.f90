 albedosi = 0.; snowonsi = 0.   ! read only with the albedo option 2 and the snow-depth option 1
 call sflx_seaice(c, 1, seaice_albedo_opt, seaice_albedo_default, seaice_snowdepth_opt, seaice_snowdepth_max, &
                  seaice_snowdepth_min, ffrozp, dt, zlvl, num_soils, sithick, lwdn, solnet, sfcprs, prcp, sfctmp, q2, &
                  th2, q2sat, dqsdt2, snoalb, tbot, z0brd, z0, emissi, t1, stc, snowh, sneqv, albedok, ch, albedosi, snowonsi, &
                  eta, sheat, eta_kinematic, fdown, esnow, dew, etp, ssoil, flx1, flx2, flx3, snomlt, sncovr, runoff1, q1, ribb)
