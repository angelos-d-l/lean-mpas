  if (t1 > 273.14) then
   q2sat = q2sat * (1.-ice%snowc(c)) + q2sati * ice%snowc(c)
   dqsdt2 = dqsdt2 * (1.-ice%snowc(c)) + q2sati * 6174. / (sfctso**2) * ice%snowc(c)
  else
   q2sat = q2sati
   dqsdt2 = q2sati * 6174. / (sfctso**2)
  endif
  if ((t1 > 273.) .and. (ice%snowc(c) > 0.0)) then
   dqsdt2 = dqsdt2 * (1. - ice%snowc(c))
  endif
 endif
 prcp = rainbl / dt
 if (frpcpn) then
  ffrozp = sr
