 !$acc routine seq
 type(state_type), intent(inout) :: state
 integer, intent(in) :: c
 type(open_water), intent(in) :: water
 real, intent(in) :: gsw, glw, raincv, z(nz+1)
 real :: interfaces(max_levels+1)
 real :: x, swdown, sfc_albedo, sfc_emiss, tsk, tsk_sea, tsk_ice, rainbl, sr, snowh, chs2, cqs2, qsfc, hfx, lh, qfx, znt, grdflx
 real :: ffrozp, zlvl, lwdn, solnet, sfcprs, prcp, sfctmp, q2, th2, q2sat, dqsdt2, snoalb, tbot, sithick, albedok
 real :: z0brd, emissi, t1, stc(num_soils), sneqv, ch, sncovr, ribb, z0, eta, sheat, eta_kinematic, fdown, esnow, dew, etp
 real :: ssoil, flx1, flx2, flx3, snomlt, runoff1, q1, apes, apelm, psfc, sfctso, e2sat, q2sati, albedosi, snowonsi
 real, parameter :: capa = R_d / cp, a2 = 17.67, a3 = 273.15, a4 = 29.65, a23m4 = a2*(a3-a4)
 integer :: ns
 call hydrostatic_interfaces_state(state, c, z, interfaces(1:nz+1))
 x = ice%xice(c)
 ! seaice_from_MPAS (mpas_atmphys_driver_seaice.F:240-287)
 swdown = gsw/(1.-ice%albedo(c))
 sfc_albedo = (ice%albedo(c) - 0.08*(1.-x)) / x
 sfc_emiss  = (ice%emiss(c) - 0.98*(1.-x)) / x
 ! correct_tsk_over_seaice (mpas_atmphys_lsm_shared.F:40-55)
 tsk_sea = state%tsk(c)
 tsk_ice = state%tsk(c)
 tsk_sea = max(tsk_sea, 271.4)
 if (x < 0.2 .and. tsk_ice < 253.15) tsk_ice = 253.15
 if (x < 0.1 .and. tsk_ice < 263.15) tsk_ice = 263.15
 tsk = tsk_ice
 ! rain and snow of the last step (mpas_atmphys_driver_seaice.F:291-313)
 rainbl = 0.
