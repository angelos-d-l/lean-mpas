 ! seaice_to_MPAS (mpas_atmphys_driver_seaice.F:386-455): blended with the open water
 state%cpm(c) = x*state%cpm(c) + (1.-x)*water%cpm
 state%chs(c)  = x*state%chs(c)  + (1.-x)*water%chs
 state%chs2(c) = x*chs2 + (1.-x)*water%chs2
 state%cqs2(c) = x*cqs2 + (1.-x)*water%cqs2
 state%hfx(c)  = x*hfx  + (1.-x)*water%hfx
 state%lh(c)   = x*lh   + (1.-x)*water%lh
 state%qfx(c)  = x*qfx  + (1.-x)*water%qfx
 state%qgh(c)  = x*state%qgh(c)  + (1.-x)*water%qgh
 state%qsfc(c) = x*qsfc + (1.-x)*water%qsfc
