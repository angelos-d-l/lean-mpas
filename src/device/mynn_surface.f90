    if(nzol+1 .le. 1000)then
      psih_unstable = psih_unstab(nzol) + rzol*(psih_unstab(nzol+1)-psih_unstab(nzol))
    else
      psih_unstable = psih_unstable_full(zolf)
    endif
  end function psih_unstable
