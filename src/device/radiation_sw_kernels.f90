zrefd(jk)= zclear*zrefdc(jk) + zcloud*zrefdo(jk)
ztra(jk) = zclear*ztrac(jk) + zcloud*ztrao(jk)
ztrad(jk)= zclear*ztradc(jk) + zcloud*ztrado(jk)
ze1 = ztauc(jk) / prmu0
if (ze1 .le. od_lo) then
zdbtmc = 1._rb - ze1 + 0.5_rb * ze1 * ze1
else
tblind = ze1 / (bpade + ze1)
itind = tblint * tblind + 0.5_rb
zdbtmc = exp_tbl(itind)
endif
zdbtc(jk) = zdbtmc
ztdbtc(jk+1) = zdbtc(jk)*ztdbtc(jk)
ze1 = ztauo(jk) / prmu0
if (ze1 .le. od_lo) then
zdbtmo = 1._rb - ze1 + 0.5_rb * ze1 * ze1
else
tblind = ze1 / (bpade + ze1)
itind = tblint * tblind + 0.5_rb
zdbtmo = exp_tbl(itind)
endif
zdbt(jk) = zclear*zdbtmc + zcloud*zdbtmo
ztdbt(jk+1) = zdbt(jk)*ztdbt(jk)
enddo
call vrtqdr_sw(klev, iw,  zrefc, zrefdc, ztrac, ztradc,  zdbtc, zrdndc, zrupc, zrupdc, ztdbtc,  ws%zcd, ws%zcu)
call vrtqdr_sw(klev, iw,  zref, zrefd, ztra, ztrad,  zdbt, zrdnd, zrup, zrupd, ztdbt,  ws%zfd, ws%zfu)
do jk=1,klev+1
ikl=klev+2-jk
pbbfu(ikl) = pbbfu(ikl) + zincflx(iw)*ws%zfu(jk,iw)
pbbfd(ikl) = pbbfd(ikl) + zincflx(iw)*ws%zfd(jk,iw)
pbbcu(ikl) = pbbcu(ikl) + zincflx(iw)*ws%zcu(jk,iw)
pbbcd(ikl) = pbbcd(ikl) + zincflx(iw)*ws%zcd(jk,iw)
pbbfddir(ikl) = pbbfddir(ikl) + zincflx(iw)*ztdbt_nodel(jk)
pbbcddir(ikl) = pbbcddir(ikl) + zincflx(iw)*ztdbtc_nodel(jk)
enddo
if (ibm >= 10 .and. ibm <= 13) then
do jk=1,klev+1
ikl=klev+2-jk
puvcd(ikl) = puvcd(ikl) + zincflx(iw)*ws%zcd(jk,iw)
