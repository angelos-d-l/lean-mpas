swhrc(iplon,i) = (swnflxc(i+1) - swnflxc(i)) * zdpgcp
swhr(iplon,i) = (swnflx(i+1) - swnflx(i)) * zdpgcp
enddo
swhrc(iplon,nlayers) = 0._rb
swhr(iplon,nlayers) = 0._rb
do i = 1, nlayers+1
swuflxcln(iplon,i) = 0.0
swdflxcln(iplon,i) = 0.0
enddo
enddo
end subroutine rrtmg_sw

