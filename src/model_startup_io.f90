 subroutine initialize(io)
 type(NoahmpIO_type),intent(inout) :: io
 io%its=1;io%ite=1;io%kts=1;io%kte=nz;io%nsoil=4;io%nsnow=3
 io%iopt_dveg=4
 io%iopt_crs=1
 io%iopt_btr=1
