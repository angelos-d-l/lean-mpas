! The NoahmpIO record the land model is driven through: initialize sets the Noah-MP options MPAS 8.4.2 uses (iopt_sfc from
! the namelist, the rest fixed as in MPAS), the defaults and the parameter tables; clear_io zeroes every allocated field of a
! record before a column is filled.
