 io%iopt_rsf=4
 io%iopt_soil=1
 io%iopt_pedo=1
 io%iopt_crop=0
 io%iopt_irr=0
 io%iopt_irrm=0
 io%iopt_infdv=1
 io%iopt_tdrn=0
 io%sf_urban_physics=0
 call NoahmpIOVarInitDefault(io)
 io%llanduse='MODIFIED_IGBP_MODIS_NOAH'
 call NoahmpReadTable(io)
 io%yr=2026;io%month=10;io%day=11   ! any valid date: the model sets the run's date (lean_model.f90), the unit tests use this one
 ! xice_threshold is not read: sea-ice cells never reach Noah-MP (sea_ice.f90)
 io%dtbl=dt;io%soiltstep=0.;io%dx=len_disp;io%xice_threshold=.5
 ! the per-step state of a running column; cold_land_column sets the first-step values (itimestep 1, restart_flag false)
 io%itimestep=2;io%restart_flag=.true.;io%fndsnowh=.true.
 end subroutine
