      b = b + card_round((((4_int64*int(mc%micro_slots,int64))*(int(mc%nz,int64)+1_int64))*6_int64))
      b = b + 3_int64*card_round(((4_int64*int(mc%micro_slots,int64))*4_int64))
  end if; end if
 case (17)   ! thompson_tables
    if (side == SIDE_HOST) then; if (mc%micro_on) then
