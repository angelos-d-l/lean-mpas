    if (side == SIDE_CARD) then; if ((mc%card_build.and.mc%any_card)) then
      b = b + card_round((((4_int64*int(mc%mynn_ldc,int64))*(int(mc%nz,int64)+1_int64))*39_int64))
      b = b + card_round(((4_int64*int(mc%mynn_ldc,int64))*17_int64))
