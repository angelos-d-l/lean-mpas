      b = b + (4_int64*(((60_int64+1_int64)*19_int64)*min(int(mc%gf_slots,int64),int(mc%micro_slots,int64))))
      b = b + (4_int64*merge(((int(mc%micro_slots,int64)*(60_int64+1_int64))*17_int64),0_int64,mc%staged_pools))
  end if; end if
    if (side == SIDE_CARD) then; if ((mc%card_build.and.(mc%any_card.or.mc%card_thompson))) then
