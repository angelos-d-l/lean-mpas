  end if; end if
 case (14)   ! micro_pools
    if (side == SIDE_HOST) then; if ((mc%card_build.and.(mc%any_card.or.mc%card_thompson))) then
      b = b + (4_int64*((int(mc%micro_slots,int64)*(60_int64+1_int64))*merge(51_int64,20_int64,mc%staged_pools)))
