      b = b + card_round(((((4_int64*int(mc%rad_slots,int64))*62_int64)*112_int64)*merge(2_int64,1_int64,mc%budget)))
      b = b + card_round((((4_int64*int(mc%rad_slots,int64))*62_int64)*14_int64))
      b = b + card_round((((8_int64*7_int64)*65_int64)*int(mc%rad_slots,int64)))
