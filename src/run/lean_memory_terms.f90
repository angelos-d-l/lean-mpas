     int64))))
      b = b + card_round(merge((((4_int64*int(mc%micro_slots,int64))*(60_int64+1_int64))*17_int64),0_int64,&
     mc%staged_pools))
  end if; end if
 case (15)   ! mynn_stage
    if (side == SIDE_HOST) then; if ((mc%card_build.and.mc%any_card)) then
      b = b + (4_int64*((int(mc%mynn_ldc,int64)*(int(mc%nz,int64)+1_int64))*39_int64))
      b = b + (4_int64*(int(mc%mynn_ldc,int64)*17_int64))
      b = b + (4_int64*(int(mc%mynn_ldc,int64)*4_int64))
      b = b + (4_int64*int(mc%mynn_ldc,int64))
      b = b + (4_int64*(((int(mc%mynn_plumes,int64)*int(mc%mynn_plumelev,int64))*8_int64)*5_int64))
