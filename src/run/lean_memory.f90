 ! The slot and chunk variables with the code's defaults and rounding (radiation_device_start in src/phys_dev.f90;
 ! micro_pool_start in src/device/micro_pool.f90; mynn_card_start in src/device/mynn_card.f90).
 subroutine slots(mc)
 type(memory_case), intent(inout) :: mc
 integer :: nch, n
 mc%rad_slots = max(1, min(env_int('LEAN_RAD_SLOTS', 2048), mc%ncells))
 mc%micro_slots = max(128, (env_int('LEAN_MICRO_SLOTS', 8192)/128)*128)
 mc%gf_slots = max(128, (env_int('LEAN_GF_SLOTS', 8192)/128)*128)
 nch = max(128, min(env_int('LEAN_MYNN_CHUNK', 12288), mc%ncells))
