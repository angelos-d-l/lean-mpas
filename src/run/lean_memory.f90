 ! The card's ledger, in bytes. Q is the moment of the check: the card is initialised and holds held_q (the runtime's
 ! context and what is loaded with the program). The run then adds the card rows not allocated at load (rows), the
 ! stack above the default size (stack) and a measured residual; full is their sum with held_q, and the headroom is
 ! max(fraction x full, minimum). free_q and total are the card's free and total memory at Q.
 type card_ledger
  integer(int64) :: held_q = 0, rows = 0, stack = 0, residual = 0, full = 0, headroom = 0, free_q = 0, total = 0
  integer(int64) :: threads = 0
  character(len=40) :: uuid = '', failed_call = ''
  integer :: status = 0                          ! the failed call's status; 0 when every call worked
 end type
 ! The host's need, in bytes: resident + max(start, step), plus a headroom of max(fraction x total, minimum).
 ! available -1: unknown, source then says why.
 type host_need
  integer(int64) :: resident = 0, start = 0, step = 0, total = 0, need = 0, headroom = 0, available = -1
  character(len=256) :: source = ''
 end type

