 ! ---- the sums --------------------------------------------------------------------------------------------------------
 ! Host = resident + max(start, step); headroom max(5 %, 512 MiB): what is used only at the start is freed before the
 ! first step.
 function host_needed(mc) result(h)
 type(memory_case), intent(in) :: mc
 type(host_need) :: h
 integer(int64) :: b
 integer :: i
 do i = 1, n_rows
  b = row_bytes(i, mc, SIDE_HOST)
  select case (row_life(i))
  case (LIFE_RESIDENT)
   h%resident = h%resident + b
  case (LIFE_START)
   h%start = h%start + b
  case (LIFE_STEP)
   h%step = h%step + b
  end select
 end do
 h%total = h%resident + max(h%start, h%step)
 h%headroom = max(int(real(h%total, 8)*host_headroom_fraction, int64), host_headroom_min)
 h%need = h%total + h%headroom
 end function

 ! The card ledger (see card_ledger): full = held_q + rows + stack + residual, headroom = max(5 % of full, 256 MiB).
 ! The run needs rows + stack + residual + headroom more than the card holds at Q.
 function card_needed(mc, frame_bytes, threads, held_q, stack_at_load, residual) result(c)
 type(memory_case), intent(in) :: mc
 integer(int64), intent(in) :: frame_bytes, threads, held_q, residual
 logical, intent(in) :: stack_at_load
 type(card_ledger) :: c
 integer :: i
 c%held_q = held_q
 c%threads = threads
 do i = 1, n_rows
  if (.not. row_at_load(i)) c%rows = c%rows + row_bytes(i, mc, SIDE_CARD)
 end do
 ! the stack above the default (card_stack_default_bytes, inside held_q), charged at the first kernel launch
 if (.not. stack_at_load) c%stack = threads*max(frame_bytes - card_stack_default_bytes, 0_int64)
 c%residual = residual
 c%full = c%held_q + c%rows + c%stack + c%residual
 c%headroom = max(int(real(c%full, 8)*card_headroom_fraction, int64), card_headroom_min)
 end function

 integer function glacier_capacity(n, cold) result(capacity)
 integer, intent(in) :: n
 logical, intent(in) :: cold
 capacity = 0
 if (n <= 0) return
 capacity = n
 if (.not. cold) return
 capacity = 64
 do while (capacity < n)
  capacity = 2*capacity
 end do
 end function

 integer function mib_up(bytes)
 integer(int64), intent(in) :: bytes
 mib_up = int((bytes + MIB - 1_int64)/MIB)
 end function

 integer function mib_down(bytes)
 integer(int64), intent(in) :: bytes
 mib_down = int(bytes/MIB)
 end function

 ! ---- what is available ---------------------------------------------------------------------------------------------
 ! root: '/' except in the unit tests. Linux: MemAvailable and every finite cgroup limit up the process's path; macOS:
 ! the free and inactive pages (an estimate: the compressor is not counted). h%available stays -1 with the reason in
 ! h%source when it cannot be read.
 subroutine host_available(h, root)
 type(host_need), intent(inout) :: h
 character(*), intent(in) :: root
 h%available = -1
 if (errno_would_block == 35 .and. root == '/') then
  call available_darwin(h)
 else if (errno_would_block == 11 .or. root /= '/') then
  call available_linux(h, root)
 else
  h%source = 'not Linux or macOS'
 end if
 end subroutine

 subroutine available_darwin(h)
 type(host_need), intent(inout) :: h
 procedure(mach_host_self_f), pointer :: host_self
 procedure(host_statistics64_f), pointer :: statistics
 procedure(getpagesize_f), pointer :: pagesize
 type(c_ptr) :: handle
 type(c_funptr) :: a, b, c
 integer(c_int) :: info(104), count, status
 handle = c_dlopen(c_null_ptr, 1_c_int)
 a = c_dlsym(handle, 'mach_host_self'//c_null_char)
 b = c_dlsym(handle, 'host_statistics64'//c_null_char)
 c = c_dlsym(handle, 'getpagesize'//c_null_char)
 if (.not. (c_associated(a) .and. c_associated(b) .and. c_associated(c))) then
  h%source = 'host_statistics64 not found'
  return
 end if
 call c_f_procpointer(a, host_self)
 call c_f_procpointer(b, statistics)
 call c_f_procpointer(c, pagesize)
 count = 104_c_int        ! HOST_VM_INFO64_COUNT of the macOS SDK (mach/host_info.h)
 info = 0
 status = statistics(host_self(), 4_c_int, info, count)   ! HOST_VM_INFO64
 if (status /= 0) then
  h%source = 'host_statistics64 returned '//int_text(int(status))
  return
 end if
 ! vm_statistics64: free_count, active_count, inactive_count are its first three 32-bit words
 h%available = (unsigned_word(info(1)) + unsigned_word(info(3)))*int(pagesize(), int64)
 h%source = 'free and inactive pages'
 end subroutine

 integer(int64) function unsigned_word(w)
 integer(c_int), intent(in) :: w
 unsigned_word = iand(int(w, int64), 4294967295_int64)
 end function

 subroutine available_linux(h, root)
 type(host_need), intent(inout) :: h
 character(*), intent(in) :: root
 ! fixed-length texts with their lengths: nvfortran 25.3 miscompiles a deferred-length string assigned from an
 ! expression that contains itself
 character(len=4096) :: line, groups(64), left, right, mount_root, point, path, level, fstype, options
 integer :: u, ios, ngroups, i, k, j, version, first, top_len, n
 integer(int64) :: limit, usage, free
 logical :: found
 found = .false.
 open(newunit=u, file=root//'proc/meminfo', status='old', action='read', iostat=ios)
 if (ios == 0) then
  do
   read(u, '(a)', iostat=ios) line
   if (ios /= 0) exit
   if (index(line, 'MemAvailable:') == 1) then
    read(line(14:), *, iostat=ios) h%available
    found = ios == 0
    exit
   end if
  end do
  close(u)
 end if
 if (.not. found) then
  h%available = -1
  h%source = 'no MemAvailable in /proc/meminfo'
  return
 end if
 h%available = h%available*1024_int64
 h%source = 'MemAvailable'
 ngroups = 0
 open(newunit=u, file=root//'proc/self/cgroup', status='old', action='read', iostat=ios)
 if (ios == 0) then
  do while (ngroups < size(groups))
   read(u, '(a)', iostat=ios) line
   if (ios /= 0) exit
   ngroups = ngroups + 1
   groups(ngroups) = line
  end do
  close(u)
 end if
 open(newunit=u, file=root//'proc/self/mountinfo', status='old', action='read', iostat=ios)
 if (ios /= 0) return
 do
  read(u, '(a)', iostat=ios) line
  if (ios /= 0) exit
  k = index(line, ' - ')
  if (k == 0) cycle
  left = line(:k-1)
  right = line(k+3:)
  fstype = word(right, 1)
  options = word(right, 3)
  version = 0
  if (trim(fstype) == 'cgroup2') version = 2
  if (trim(fstype) == 'cgroup' .and. index(','//trim(options)//',', ',memory,') > 0) version = 1
  if (version == 0) cycle
  mount_root = word(left, 4)
  point = word(left, 5)
  path = ''
  do i = 1, ngroups
   if (version == 2 .and. index(groups(i), '0::') == 1) path = groups(i)(4:)
   if (version == 1) then
    k = index(groups(i), ':')
    if (k == 0) cycle
    j = index(groups(i)(k+1:), ':') + k            ! the second ':'
    if (j == k) cycle
    if (index(','//groups(i)(k+1:j-1)//',', ',memory,') > 0) path = groups(i)(j+1:)
   end if
  end do
  if (len_trim(path) == 0) cycle
  ! the process's path below the mount's root, without leading '/'
  first = 1
  if (index(path, trim(mount_root)) == 1) first = len_trim(mount_root) + 1
  do while (first <= len_trim(path))
   if (path(first:first) /= '/') exit
   first = first + 1
  end do
  top_len = len(root) + len_trim(point) - 1
  if (first <= len_trim(path)) then
   level = root//trim(point(2:))//'/'//path(first:len_trim(path))
  else
   level = root//trim(point(2:))
  end if
  n = len_trim(level)
  do
   if (version == 2) then
    limit = file_number(level(:n)//'/memory.max')
    usage = file_number(level(:n)//'/memory.current')
   else
    limit = file_number(level(:n)//'/memory.limit_in_bytes')
    usage = file_number(level(:n)//'/memory.usage_in_bytes')
   end if
   if (limit >= 0 .and. limit < 4611686018427387904_int64) then
    free = max(0_int64, limit - max(0_int64, usage))
    if (free < h%available) then
     h%available = free
     if (n > top_len) then
      h%source = 'cgroup '//level(top_len+1:n)
     else
      h%source = 'cgroup /'
     end if
    end if
   end if
   if (n <= top_len) exit
   n = index(level(:n), '/', back=.true.) - 1
   if (n < top_len) n = top_len
  end do
 end do
 close(u)
 end subroutine

 ! The i-th blank-separated word of text ('' when there are fewer).
 function word(text, i) result(w)
 character(*), intent(in) :: text
 integer, intent(in) :: i
 character(len=4096) :: w
 integer :: n, first, p
 w = ''
 n = 0
 p = 1
 do while (p <= len_trim(text))
  do while (p <= len_trim(text))
   if (text(p:p) /= ' ') exit
   p = p + 1
  end do
  if (p > len_trim(text)) exit
  first = p
  do while (p <= len_trim(text))
   if (text(p:p) == ' ') exit
   p = p + 1
  end do
  n = n + 1
  if (n == i) then
   w = text(first:p-1)
   return
  end if
 end do
 end function

 ! The first number of a file; -1 when it is missing, empty or not a number ('max').
 integer(int64) function file_number(path) result(n)
 character(*), intent(in) :: path
 character(len=256) :: line
 integer :: u, ios
 n = -1
 open(newunit=u, file=path, status='old', action='read', iostat=ios)
 if (ios /= 0) return
 read(u, '(a)', iostat=ios) line
 close(u)
 if (ios /= 0) return
 read(line, *, iostat=ios) n
 if (ios /= 0) n = -1
 end function

 ! The card at Q: acc_init on device 0, then cudaMemGetInfo, the SM count and threads per SM, the UUID.
 ! A failed call is named in c%failed_call with its status.
 subroutine card_available(c)
 type(card_ledger), intent(inout) :: c
#ifdef _OPENACC
 integer(c_size_t) :: free, total
 integer(c_int) :: status, sms, per_sm
 integer(c_int8_t) :: prop(4096)
 integer :: i
 character(len=*), parameter :: hex = '0123456789abcdef'
 integer :: byte
 call acc_init_c(4_c_int)            ! acc_device_nvidia of NVHPC's openacc.h
 status = cudaMemGetInfo(free, total)
 if (status /= 0) then
  c%failed_call = 'cudaMemGetInfo'
  c%status = int(status)
  return
 end if
 status = cudaDeviceGetAttribute(sms, 16_c_int, 0_c_int)            ! cudaDevAttrMultiProcessorCount
 if (status == 0) status = cudaDeviceGetAttribute(per_sm, 39_c_int, 0_c_int)   ! cudaDevAttrMaxThreadsPerMultiProcessor
 if (status /= 0) then
  c%failed_call = 'cudaDeviceGetAttribute'
  c%status = int(status)
  return
 end if
 c%free_q = int(free, int64)
 c%total = int(total, int64)
 c%threads = int(sms, int64)*int(per_sm, int64)
 prop = 0
 status = cudaGetDeviceProperties(prop, 0_c_int)
 if (status == 0) then
  ! cudaDeviceProp: char name[256], then cudaUUID_t uuid (16 bytes), as nvidia-smi writes it: GPU-8-4-4-4-12 hex digits
  c%uuid = 'GPU-'
  do i = 1, 16
   byte = iand(int(prop(256+i)), 255)
   c%uuid = trim(c%uuid)//hex(byte/16+1:byte/16+1)//hex(mod(byte, 16)+1:mod(byte, 16)+1)
   if (i == 4 .or. i == 6 .or. i == 8 .or. i == 10) c%uuid = trim(c%uuid)//'-'
  end do
 end if
#else
 c%failed_call = 'no OpenACC in this build'
 c%status = -1
#endif
 end subroutine

 ! ---- verdicts --------------------------------------------------------------------------------------------------------
 ! An ERR line (text) when need passes what is available and the check is enforced, a warning when it is not;
 ! nothing when it fits. need is with its headroom; available -1 is unknown (no verdict).
 subroutine memory_verdict(side, need, headroom, available, enforce, text, msgs)
 integer, intent(in) :: side
 integer(int64), intent(in) :: need, headroom, available
 logical, intent(in) :: enforce
 character(*), intent(in) :: text
 type(message_list), intent(inout) :: msgs
 if (available < 0 .or. need <= available) return
 if (enforce) then
  call add_message(msgs, LOG_ERR, text)
 else
  if (side == SIDE_HOST) then
   call add_message(msgs, LOG_WARN, 'config_lean_memory_check = .false.: lean_mpas goes on although the mesh does not '// &
                    'fit in host memory ('//int_text(mib_up(need))//' MiB needed, '//int_text(mib_down(available))// &
                    ' MiB available).')
  else
   call add_message(msgs, LOG_WARN, 'config_lean_memory_check = .false.: lean_mpas goes on although the mesh does not '// &
                    'fit on the card ('//int_text(mib_up(need))//' MiB needed, '//int_text(mib_down(available))// &
                    ' MiB available).')
  end if
 end if
 end subroutine

 ! ---- the run's facts --------------------------------------------------------------------------------------------------
 ! The case from the mesh file's dimensions, the preview, the start record and the environment. ok = .false. when it
 ! cannot be made (a dimension missing, a file that does not open, no start record): the reads after it report that.
 ! A field the glacier count needs that is missing from its file gives lean's input message, an ERR line.
 subroutine memory_case_from(cfg, private_clock, preview, mesh_file, mc, ok, msgs, slab_width)
 type(run_config), intent(in) :: cfg
 type(run_clock), intent(in) :: private_clock
 type(stream_set), intent(in) :: preview
 character(*), intent(in) :: mesh_file
 type(memory_case), intent(out) :: mc
 logical, intent(out) :: ok
 type(message_list), intent(inout) :: msgs
 integer, intent(in), optional :: slab_width
 type(nc_file) :: f
 type(input_file) :: init, mesh
 type(message_list) :: dropped
 character(len=:), allocatable :: init_path, restart_path
 character(len=19) :: stamp
 character(len=32) :: env
 integer :: i, status, width, n
 logical :: found, same
 ok = .false.
 width = SLAB
 if (present(slab_width)) width = slab_width
 if (nc_open(f, trim(mesh_file)) /= NC_NOERR) return
 mc%ncells = dimension_of(f, 'nCells')
 mc%nedges = dimension_of(f, 'nEdges')
 mc%nvertices = dimension_of(f, 'nVertices')
 mc%nz = dimension_of(f, 'nVertLevels')
 status = nc_close(f)
 if (min(mc%ncells, mc%nedges, mc%nvertices, mc%nz) < 1 .or. mc%nz > 60) return
 mc%cold = .not. cfg%config_do_restart
 mc%apply_lbcs = cfg%config_apply_lbcs
 mc%micro_on = trim(cfg%config_microp_scheme) /= 'off'
 mc%moist_physics = cfg%moist_physics
 ! the glacier columns: the rule of a start from the init file (start_glacier's caller in src/lean_model.f90) on the
 ! start record; a restart's own count
 if (mc%cold) then
  i = stream_index(preview, 'input')
  if (i == 0) return
  if (.not. read_filename(preview, i, private_clock%start, init_path, dropped)) init_path = trim(preview%s(i)%template)
  if (nc_open(init%nc, init_path) /= NC_NOERR) return
  init%path = init_path
  init%role = 'input'
  init%opened = .true.
  call seek_record(init, time_string(private_clock%start), .true., dropped, found, stamp)
  if (.not. found) then
   status = nc_close(init%nc)
   return
  end if
  same = trim(mesh_file) == init_path
  if (.not. same) then
   if (nc_open(mesh%nc, trim(mesh_file)) /= NC_NOERR) then
    status = nc_close(init%nc)
    return
   end if
   mesh%path = mesh_file
   mesh%role = 'input'
   mesh%opened = .true.
   call seek_record(mesh, time_string(private_clock%start), .false., dropped, found, stamp)   ! the closest time
   if (.not. found) mesh%record = min(1, dimension_of(mesh%nc, 'Time'))
  end if
  n = count_glacier(init, mesh, same, mc%ncells, width, msgs)
  if (.not. same) status = nc_close(mesh%nc)
  status = nc_close(init%nc)
  if (n < 0) return
  mc%n_glacier = n
 else
  i = stream_index(preview, 'restart')
  if (i == 0) return
  if (.not. read_filename(preview, i, private_clock%start, restart_path, dropped)) &
   restart_path = trim(preview%s(i)%template)
  if (nc_open(f, restart_path) /= NC_NOERR) return
  mc%n_glacier = max(0, dimension_of(f, 'lean_nGlacierCells'))
  status = nc_close(f)
 end if
 mc%glacier_capacity = glacier_capacity(mc%n_glacier, mc%cold)
 ! the build and the environment
 mc%card_build = build_openacc
 if (mc%card_build) call requested_stages(mc)
 mc%staged_pools = .true.
#ifdef LEAN_MICRO_ONEKERNEL
 call get_environment_variable('LEAN_MICRO_STAGED', env, status=status)
 mc%staged_pools = status == 0 .and. trim(env) == '1'
#endif
#ifdef LEAN_BUDGET
 mc%budget = .true.
#endif
#ifdef LEAN_NOAHMP_SWSPLIT
 mc%swsplit = .true.
#endif
 call slots(mc)
 mc%products = env_set('LEAN_PRODUCTS')
 mc%film = env_set('LEAN_FILM') .or. mc%products
 mc%storm = env_set('LEAN_STORM')
 mc%surface = env_set('LEAN_SURFACE')
 mc%maxima = mc%storm
 call writer_sizes(preview, mesh_file, mc)
 ok = .true.
 end subroutine

 integer function dimension_of(f, name) result(n)
 type(nc_file), intent(inout) :: f
 character(*), intent(in) :: name
 if (nc_inq_dim(f, name, n) /= NC_NOERR) n = 0
 end function

 ! The cells of the glacier rule, xice and xland of the start record, ivgtyp of the mesh file's, in slabs of width
 ! cells (mesh is not used when same: the mesh is the init file); -1 with lean's input message when a field is missing.
 integer function count_glacier(init, mesh, same, ncells, width, msgs) result(n)
 type(input_file), intent(inout) :: init, mesh
 logical, intent(in) :: same
 integer, intent(in) :: ncells, width
 type(message_list), intent(inout) :: msgs
 real, save :: xice(SLAB), xland(SLAB)
 integer, save :: ivgtyp(SLAB)
 integer :: first, k, status(3), c
 n = -1
 if (.not. has_field(init, 'xice', msgs)) return
 if (.not. has_field(init, 'xland', msgs)) return
 if (same) then
  if (.not. has_field(init, 'ivgtyp', msgs)) return
 else
  if (.not. has_field(mesh, 'ivgtyp', msgs)) return
 end if
 n = 0
 first = 1
 do while (first <= ncells)
  k = min(width, SLAB, ncells - first + 1)
  status(1) = slab_real(init, 'xice', first, k, xice)
  status(2) = slab_real(init, 'xland', first, k, xland)
  if (same) then
   status(3) = slab_int(init, 'ivgtyp', first, k, ivgtyp)
  else
   status(3) = slab_int(mesh, 'ivgtyp', first, k, ivgtyp)
  end if
  if (any(status /= NC_NOERR)) then
   n = -1
   return
  end if
  do c = 1, k
   if (xice(c) < XICE_THRESHOLD .and. xland(c) < 1.5 .and. ivgtyp(c) == GLACIER_CATEGORY) n = n + 1
  end do
  first = first + k
 end do
 end function

