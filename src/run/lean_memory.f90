 nch = (((mc%ncells + n - 1)/n + 31)/32)*32
 mc%mynn_ldc = ((nch + 31)/32)*32
 mc%mynn_plumes = max(128, min(env_int('LEAN_MYNN_PLUMES', 8192), mc%mynn_ldc))
 mc%mynn_plumelev = max(2, min(env_int('LEAN_MYNN_PLUMELEV', 16), mc%nz - 1))
 end subroutine

 ! The writer's sizes as output_start computes them (output_start in src/lean_fields.f90): the largest field of an active output
 ! stream other than restart (floor nCells), and the held fields of at most nCells elements.
 subroutine writer_sizes(preview, mesh_file, mc)
 type(stream_set), intent(in) :: preview
 character(*), intent(in) :: mesh_file
 type(memory_case), intent(inout) :: mc
 type(nc_file) :: f
 character(len=32), allocatable :: names(:)
 character(len=48) :: definition
 integer :: lengths(N_DIMS), d, i, j, k, v, n, status, ios, mask, p
 integer(int64) :: elements(N_VARS)
 lengths = 0
 status = nc_open(f, trim(mesh_file))
 do d = 1, N_DIMS
  if (status == NC_NOERR) then
   if (nc_inq_dim(f, trim(DIM_NAME(d)), n) == NC_NOERR) then
    lengths(d) = n
    cycle
   end if
  end if
  definition = DIM_DEFINITION(d)
  read(definition, *, iostat=ios) n
  if (ios == 0) lengths(d) = n
  select case (trim(DIM_NAME(d)))
  case ('nVertLevels'); lengths(d) = mc%nz
  case ('nVertLevelsP1'); lengths(d) = mc%nz + 1
  case ('nVertLevelsP2'); lengths(d) = mc%nz + 2
  case ('nMonths'); lengths(d) = 12
  case ('nSoilLevels'); lengths(d) = 4
  case ('nzSnowLevels'); lengths(d) = 7
  case ('nOznLevels'); lengths(d) = 59
  case ('nAerLevels'); lengths(d) = 29
  case ('cam_dim1'); lengths(d) = 1
  case ('nLags'); lengths(d) = 0
  end select
 end do
 if (status == NC_NOERR) status = nc_close(f)
 do v = 1, N_VARS
  elements(v) = 1
  definition = VAR_DIMS(v)
  do while (len_trim(definition) > 0)
   j = index(trim(definition)//' ', ' ')
   do d = 1, N_DIMS
    if (trim(DIM_NAME(d)) == definition(:j-1)) elements(v) = elements(v)*lengths(d)
   end do
   definition = adjustl(definition(j:))
  end do
 end do
 mask = 0
 do p = 1, N_PACKAGES
  if (preview%package(p)) mask = ibset(mask, p-1)
 end do
 mc%largest_output = mc%ncells
 do i = 1, preview%n
  if (.not. preview%s(i)%active) cycle
  if (preview%s(i)%direction /= STREAM_OUTPUT .and. preview%s(i)%direction /= STREAM_INPUT_OUTPUT) cycle
  if (trim(preview%s(i)%name) == 'restart') cycle
  call stream_fields(preview, i, names)
  do j = 1, size(names)
   k = field_index(names(j))
   if (k == 0) cycle
   do v = FIELD_FIRST_VAR(k), FIELD_FIRST_VAR(k) + FIELD_VAR_COUNT(k) - 1
    if (VAR_PACKAGES(v) /= 0 .and. iand(VAR_PACKAGES(v), mask) == 0) cycle
    mc%largest_output = max(mc%largest_output, elements(v))
   end do
  end do
 end do
 mc%held = 0
 do v = 1, N_VARS
  if (elements(v) > mc%ncells) cycle
  if (any(held_names == VAR_NAME(v)) .or. (mc%cold .and. any(start_names == VAR_NAME(v)))) mc%held = mc%held + 1
 end do
 end subroutine

 ! ---- the check ---------------------------------------------------------------------------------------------------
 ! The check's summary lines, the verdicts, and the stop line when one of them is an ERR. Nothing is said when the case
 ! cannot be made. LEAN_MEMORY_REPORT=1 prints the lines and the case, then stops with status 0.
 subroutine check_memory(cfg, clock, nsteps, namelist_path, set, msgs)
 type(run_config), intent(in) :: cfg
 type(run_clock), intent(in) :: clock
 integer, intent(in) :: nsteps
 character(*), intent(in) :: namelist_path
 type(stream_set), intent(in) :: set
 type(message_list), intent(inout) :: msgs
 type(run_clock) :: private_clock
 type(stream_set) :: preview
 type(message_list) :: dropped, report
 type(memory_case) :: mc
 type(host_need) :: h
 type(card_ledger) :: c, q
 character(len=:), allocatable :: doctor, file
 integer :: problems, first, i
 logical :: ok, enforce
 call clock_from_config(cfg, private_clock, dropped)
 if (has_fatal(dropped)) return
 call streams_preview(set, cfg, private_clock, preview, ok)
 if (.not. ok) return
 first = msgs%n
 call memory_case_from(cfg, private_clock, preview, trim(set%mesh_file), mc, ok, msgs)
 if (.not. ok) return
 enforce = cfg%config_lean_memory_check
 file = trim(set%mesh_file)
 doctor = './lean doctor --init '//file//' --namelist '//namelist_path//' --streams '//trim(set%path)// &
          ' --build build/'//trim(build_name)
 h = host_needed(mc)
 call host_available(h, '/')
#ifdef LEAN_MEMORY_TEST
 call test_available(h, c)
#endif
 call add_message(msgs, LOG_OUT, 'Memory check: nCells '//int_text(mc%ncells)//', nEdges '//int_text(mc%nedges)// &
                  ', nVertices '//int_text(mc%nvertices)//', nVertLevels '//int_text(mc%nz)//', '// &
                  int_text(mc%n_glacier)//' glacier columns')
 if (h%available >= 0) then
  call add_message(msgs, LOG_OUT, '  host: '//int_text(mib_up(h%need))//' MiB needed ('//int_text(mib_up(h%total))// &
                   ' MiB and '//int_text(mib_up(h%headroom))//' MiB headroom), '//int_text(mib_down(h%available))// &
                   ' MiB available ('//trim(h%source)//')')
 else
  call add_message(msgs, LOG_OUT, '  host: '//int_text(mib_up(h%need))//' MiB needed ('//int_text(mib_up(h%total))// &
                   ' MiB and '//int_text(mib_up(h%headroom))//' MiB headroom), available unknown')
 end if
 if (mc%card_build) then
#ifdef LEAN_MEMORY_TEST
  if (c%total == 0) call card_available(c)
#else
  call card_available(c)
#endif
  q = card_needed(mc, int(card_frame_bytes, int64), c%threads, card_held_q_bytes, card_stack_at_load, &
                  card_residual_bytes)
  if (len_trim(c%failed_call) == 0) then
   q%free_q = c%free_q
   q%total = c%total
   q%uuid = c%uuid
   call add_message(msgs, LOG_OUT, '  card '//trim(q%uuid)//': '//int_text(mib_up(more(q)))// &
                    ' MiB more needed (rows '//int_text(mib_up(q%rows))//', stack '//int_text(mib_up(q%stack))// &
                    ' for '//int_text(int(q%threads))//' threads, residual '//int_text(mib_up(q%residual))// &
                    ', headroom '//int_text(mib_up(q%headroom))//'), '//int_text(mib_down(q%free_q))//' MiB free of '// &
                    int_text(mib_down(q%total))//' MiB now')
  else
   call add_message(msgs, LOG_OUT, '  card: unknown')
  end if
 end if
 if (env_set('LEAN_CHECK')) &
  call add_message(msgs, LOG_WARN, 'LEAN_CHECK is set: the memory check does not count the copies it makes.')
 if (h%available < 0) call add_message(msgs, LOG_WARN, 'lean_mpas cannot tell how much host memory is available ('// &
                                       trim(h%source)//'): the host part of the memory check is not made.')
 call memory_verdict(SIDE_HOST, h%need, h%headroom, h%available, enforce, &
  'The mesh of '//file//' does not fit in host memory: lean_mpas needs '//int_text(mib_up(h%need))//' MiB (with '// &
  int_text(mib_up(h%headroom))//' MiB headroom) and '//int_text(mib_down(h%available))//' MiB are available ('// &
  trim(h%source)//'). It stops before allocating the mesh; '//doctor//' lists what the sum is made of.', msgs)
 if (mc%card_build) call card_verdict(c, q, enforce, &
  'The mesh of '//file//' does not fit on the card: lean_mpas needs '//int_text(mib_up(more(q)))//' MiB more (with '// &
  int_text(mib_up(q%headroom))//' MiB headroom) and '//int_text(mib_down(q%free_q))//' MiB of the card''s '// &
  int_text(mib_down(q%total))//' MiB are free now. It stops before allocating the mesh; '//doctor// &
  ' lists what the sum is made of.', msgs)
 problems = 0
 do i = first + 1, msgs%n
  if (msgs%line(i)%level == LOG_ERR) problems = problems + 1
 end do
 if (problems > 0) call add_message(msgs, LOG_CRIT, 'lean_mpas stops: '//int_text(problems)//' memory problem(s) listed above')
 if (env_set('LEAN_MEMORY_REPORT')) then
  do i = first + 1, msgs%n
   call add_message(report, msgs%line(i)%level, msgs%line(i)%text)
  end do
  call write_messages(output_unit, report)
  call write_case(mc, output_unit)
  stop
 end if
 end subroutine

 ! The card's verdict: when a call failed (c%failed_call) an ERR line, or a warning without enforce; else
 ! memory_verdict. q: the ledger of card_needed; text: the sentence when the mesh does not fit.
 subroutine card_verdict(c, q, enforce, text, msgs)
 type(card_ledger), intent(in) :: c, q
 logical, intent(in) :: enforce
 character(*), intent(in) :: text
 type(message_list), intent(inout) :: msgs
 if (len_trim(c%failed_call) > 0) then
  if (enforce) then
   call add_message(msgs, LOG_ERR, 'lean_mpas cannot read the card''s memory ('//trim(c%failed_call)//' returned '// &
                    int_text(c%status)//'): set config_lean_memory_check = .false. in &lean to run without the card '// &
                    'part of the check.')
  else
   call add_message(msgs, LOG_WARN, 'config_lean_memory_check = .false.: lean_mpas goes on although the card''s memory '// &
                    'could not be read ('//int_text(mib_up(more(q)))//' MiB needed, available unknown).')
  end if
 else
  call memory_verdict(SIDE_CARD, more(q), q%headroom, q%free_q, enforce, text, msgs)
 end if
 end subroutine

 integer(int64) function more(q)
 type(card_ledger), intent(in) :: q
 more = q%rows + q%stack + q%residual + q%headroom
 end function

