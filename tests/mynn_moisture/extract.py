"""Write the two 2 m diagnostic modules of the column harness into OUTDIR, as text copies of the sources:

  python3 tests/mynn_moisture/extract.py OUTDIR host|card MPAS_PHYSICS_DIR [NOAHMP_COUPLING_SOURCE]

sfc_diag_lean.f90: subroutine surface_diagnostics of src/noahmp_coupling.f90 (host) or src/device/noahmp_coupling.f90
(card), unchanged, with a stand-in for the four Noah-MP 2 m fields it reads (noahmp_column).
sfc_diag_mpas.f90: the loop of the sf_noahmp branch of atmphys_sfc_diagnostics (mpas_atmphys_sfc_diagnostics.F),
unchanged, in a subroutine over one cell; the pool pointers become arguments.
"""
import sys
from pathlib import Path

root = Path(__file__).resolve().parents[2]
out, side, phys = Path(sys.argv[1]), sys.argv[2], Path(sys.argv[3])
name = 'src/device/noahmp_coupling.f90' if side == 'card' else 'src/noahmp_coupling.f90'
src = (Path(sys.argv[4]) if len(sys.argv) > 4 else root / name).read_text()
a = src.index(' subroutine surface_diagnostics(')
b = src.index(' end subroutine', a) + len(' end subroutine')
(out / 'sfc_diag_lean.f90').write_text('''! GENERATED by tests/mynn_moisture/extract.py from %s
module sfc_diag_lean
 use model_state
 use mpas_atmphys_constants,only: cp,P0,R_d,rcp
 implicit none
 type noahmp_column   ! the four Noah-MP fields surface_diagnostics reads
  real :: energy_state_SpecHumidity2mVeg,energy_state_SpecHumidity2mBare,energy_state_VegFrac,energy_state_TemperatureAir2m
 end type
contains
%s
end module
''' % (name, src[a:b]))

f = (phys / 'mpas_atmphys_sfc_diagnostics.F').read_text()
a = f.index('case("sf_noahmp")')
loop = f[f.index('do i = 1,nCellsSolve', a):f.index('case default', a)].rstrip()
assert loop.endswith('enddo'), 'the sf_noahmp loop of mpas_atmphys_sfc_diagnostics.F changed'
(out / 'sfc_diag_mpas.f90').write_text('''! GENERATED by tests/mynn_moisture/extract.py from mpas_atmphys_sfc_diagnostics.F (sf_noahmp branch)
module sfc_diag_mpas
 use mpas_kind_types,only: RKIND
 use mpas_atmphys_constants,only: cp,P0,R_d,rcp
 implicit none
contains
 subroutine mpas_sfc_diagnostics(psfc,tsk,xland,xice,chs2,cqs2,hfx,qfx,qsfc,q2mxy,t2mxy,q2,t2m,th2m)
 real(kind=RKIND),dimension(1),intent(in) :: psfc,tsk,xland,xice,chs2,cqs2,hfx,qfx,qsfc,q2mxy,t2mxy
 real(kind=RKIND),dimension(1),intent(inout) :: q2,t2m,th2m
 real(kind=RKIND),parameter :: xice_threshold=0.5
 integer,parameter :: nCellsSolve=1
 integer :: i
 real(kind=RKIND) :: rho
%s
 end subroutine
end module
''' % loop)
print('wrote', out / 'sfc_diag_lean.f90', out / 'sfc_diag_mpas.f90')
