"""Write the pool code of the land-ice test (tests/land_ice/run.sh) from the unchanged MPAS Noah-MP driver.

  python3 tests/land_ice/pools.py PHYSICS_DIR OUT_DIR

Reads mpas_atmphys_driver_lsm_noahmp.F and writes OUT_DIR/pools.inc, the body of module land_ice_pools:
- one array per pool field the driver reads (ncol cells, levels as MPAS keeps them) and register_pools, which registers
  cell c of each in the pool stand-in (tests/dyn_pool.f90): each test column is a block of one cell;
- set_pools_from_io: the pool values of a cold start, each pool field set from the NoahmpIO field the driver copies it to
  (every `mpas_noahmp%x(i) = pool(i)` line of lsm_noahmp_fromMPAS, reversed);
- compare_pools: every field lsm_noahmp_toMPAS writes, the pool against lean's NoahmpIO column, bit for bit.
Nothing here is lean code; the lists come from the driver itself, so a field it reads or writes cannot be left out.
"""
import re
import sys
from pathlib import Path

phys, out = Path(sys.argv[1]), Path(sys.argv[2])
src = (phys / 'mpas_atmphys_driver_lsm_noahmp.F').read_text()
subs = {m.group(1).lower(): m.group(2) for m in re.finditer(r'\n\s*subroutine\s+(\w+)\s*\((.*?)\n\s*end subroutine', src, re.S | re.I)}


def declarations(body):
    """local pointer name -> (type, rank)"""
    decl = {}
    text = re.sub(r'&\s*\n\s*', ' ', body)
    for m in re.finditer(r'^\s*(real\(kind=RKIND\)|integer|logical|character\(len=StrKIND\))\s*(?:,\s*dimension\(([:,]+)\))?\s*,\s*pointer\s*::(.*)$', text, re.M):
        rank = m.group(2).count(':') if m.group(2) else 0
        for v in m.group(3).split('!')[0].split(','):
            if v.strip():
                decl[v.strip().lower()] = (m.group(1).split('(')[0], rank)
    return decl


fields = {}   # (pool, name) -> (type, rank, variable)
links = {}    # pool variable -> (pool, name)
for sub in ('lsm_noahmp_frommpas', 'lsm_noahmp_sounding_frommpas', 'lsm_noahmp_tompas'):
    body = subs[sub]
    decl = declarations(body)
    for pool, name, var in re.findall(r"call\s+mpas_pool_get_array\s*\(\s*(\w+)\s*,\s*'\s*(\w+)\s*'\s*,\s*(\w+)", body, re.I):
        kind, rank = decl[var.lower()]
        fields[(pool, name)] = (kind, rank, var.lower())
        links.setdefault((sub, var.lower()), (pool, name))
# array extents, by field: (levels, cells) as in the MPAS Registry
levels = {'sh2o': 'nsoil', 'smois': 'nsoil', 'tslb': 'nsoil', 'tsnoxy': 'nsnow', 'snicexy': 'nsnow', 'snliqxy': 'nsnow',
          'zsnsoxy': 'nzsnow', 'acc_etranixy': 'nsoil', 'zgrid': 'nlev+1', 'exner': 'nlev', 'pressure_base': 'nlev',
          'pressure_p': 'nlev', 'uReconstructMeridional': 'nlev', 'uReconstructZonal': 'nlev', 'theta_m': 'nlev'}
lines = ['! generated by tests/land_ice/pools.py from mpas_atmphys_driver_lsm_noahmp.F; do not edit']
for (pool, name), (kind, rank, var) in sorted(fields.items()):
    t = {'real': 'real(kind=RKIND)', 'integer': 'integer'}[kind]
    shape = '(ncol)' if rank == 1 else f'({levels[name]},ncol)' if rank == 2 else '(nscal,nlev,ncol)'
    lines.append(f' {t}, target :: p_{pool}_{name}{shape}')
lines += [' integer, target :: p_index_qv = 1', 'contains', ' subroutine register_pools(s, c)', ' type(pool_set), intent(inout) :: s',
          ' integer, intent(in) :: c', ' call clear_pools(s)']
for (pool, name), (kind, rank, var) in sorted(fields.items()):
    cut = {1: '(c:c)', 2: '(:,c:c)', 3: '(:,:,c:c)'}[rank]
    level = ', 1' if pool == 'state' else ''   # the physics reads the state at time level 1
    lines.append(f"  call pool_put(s%{pool}, '{name}', p_{pool}_{name}{cut}{level})")
lines += ["  call pool_put_dimension(s%state, 'index_qv', p_index_qv)", ' end subroutine']
# cold start: pool = NoahmpIO for every copy of lsm_noahmp_fromMPAS
lines += [' subroutine set_pools_from_io(io, c)', ' type(NoahmpIO_type), intent(in) :: io', ' integer, intent(in) :: c', ' integer :: ns, n']
body = re.sub(r'&\s*\n\s*', ' ', subs['lsm_noahmp_frommpas'])
copies = 0
for m in re.finditer(r'^\s*mpas_noahmp%(\w+)\(([^)]*)\)\s*=\s*(\w+)\(([^)]*)\)\s*$', body, re.M):
    target, tix, var, six = m.groups()
    if ('lsm_noahmp_frommpas', var.lower()) not in links:
        continue
    pool, name = links[('lsm_noahmp_frommpas', var.lower())]
    rank = fields[(pool, name)][1]
    if rank == 1:
        lines.append(f'  p_{pool}_{name}(c) = io%{target}(1)')
    elif tix.replace(' ', '') == 'i,ns':
        lines.append(f'  do ns = 1, size(p_{pool}_{name}, 1); p_{pool}_{name}(ns,c) = io%{target}(1,ns); end do')
    elif tix.replace(' ', '') == 'i,n':
        lines.append(f'  do ns = 1, size(p_{pool}_{name}, 1); n = ns - 3; p_{pool}_{name}(ns,c) = io%{target}(1,n); end do')
    else:
        raise SystemExit(f'pools.py: unexpected index {tix} in {m.group(0)}')
    copies += 1
lines.append(' end subroutine')
# after each step: every field lsm_noahmp_toMPAS writes, pool against NoahmpIO
lines += [' subroutine compare_pools(io, c, bad, names, nf)', ' type(NoahmpIO_type), intent(in) :: io', ' integer, intent(in) :: c',
          ' integer, intent(inout) :: bad(:)', ' character(24), intent(out) :: names(:)', ' integer, intent(out) :: nf',
          ' integer :: ns, n', ' nf = 0']
body = re.sub(r'&\s*\n\s*', ' ', subs['lsm_noahmp_tompas'])
compared = 0
for m in re.finditer(r'^\s*(\w+)\(([^)]*)\)\s*=\s*mpas_noahmp%(\w+)\(([^)]*)\)\s*$', body, re.M):
    var, six, target, tix = m.groups()
    pool, name = links[('lsm_noahmp_tompas', var.lower())]
    rank = fields[(pool, name)][1]
    lines.append(f"  nf = nf + 1; names(nf) = '{name}'")
    if rank == 1:
        lines.append(f'  if (differ(p_{pool}_{name}(c), io%{target}(1))) bad(nf) = bad(nf) + 1')
    elif tix.replace(' ', '') == 'i,ns':
        lines.append(f'  do ns = 1, size(p_{pool}_{name}, 1); if (differ(p_{pool}_{name}(ns,c), io%{target}(1,ns))) bad(nf) = bad(nf) + 1; end do')
    else:
        lines.append(f'  do ns = 1, size(p_{pool}_{name}, 1); n = ns - 3; if (differ(p_{pool}_{name}(ns,c), io%{target}(1,n))) bad(nf) = bad(nf) + 1; end do')
    compared += 1
lines.append(' end subroutine')
(out / 'pools.inc').write_text('\n'.join(lines) + '\n')
print(f'pools.py: {len(fields)} pool fields, {copies} start copies, {compared} compared fields')
